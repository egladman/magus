package emit

import (
	"bytes"
	"fmt"
	"reflect"
	"strings"

	"github.com/egladman/magus/libs/gopherbuzz/buzzgen"
)

// TSType is one boundary type written as TypeScript: its mirror name
// and its Go type.
type TSType struct {
	Name string
	Type reflect.Type
}

// TSTypes renders entries in order. A plain struct becomes an
// interface over its JSON shape. Result becomes a union narrowed on
// `error`, with MagusError as its default error. name gives a nested
// struct's mirror name, which an earlier entry must declare.
func TSTypes(entries []TSType, name func(reflect.Type) string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by magus-utils tstypes. DO NOT EDIT.")
	fmt.Fprintln(&b, "//")
	fmt.Fprintln(&b, "// TypeScript forms of the boundary types flagged TS in cmd/magus-utils/boundary_types.go.")
	fmt.Fprintln(&b, "// Edit the Go struct and run `magus run types-generate`, never this file.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, `import { Code, ConnectError } from "@connectrpc/connect";`)
	declared := map[string]bool{}
	for _, e := range entries {
		fmt.Fprintln(&b)
		if len(buzzgen.TypeParams(e.Type)) > 0 {
			if e.Name != "Result" {
				return nil, fmt.Errorf("boundary type %s: no TypeScript form for a generic other than Result", e.Name)
			}
			if !declared["Diagnostic"] {
				return nil, fmt.Errorf("boundary type Result: Diagnostic must be flagged TS and precede it")
			}
			b.WriteString(tsResult)
			declared[e.Name] = true
			continue
		}
		if err := tsInterface(&b, e, declared, name); err != nil {
			return nil, fmt.Errorf("boundary type %s: %w", e.Name, err)
		}
		declared[e.Name] = true
	}
	return b.Bytes(), nil
}

// tsInterface writes e's JSON shape. It leaves out a field the Buzz
// mirror opts out of, as both describe the value at the boundary.
func tsInterface(b *bytes.Buffer, e TSType, declared map[string]bool, name func(reflect.Type) string) error {
	fmt.Fprintf(b, "export interface %s {\n", e.Name)
	for i := 0; i < e.Type.NumField(); i++ {
		f := e.Type.Field(i)
		if !f.IsExported() || f.Tag.Get("buzz") == "-" {
			continue
		}
		jsonName, opts, _ := strings.Cut(f.Tag.Get("json"), ",")
		if jsonName == "-" {
			continue
		}
		if jsonName == "" {
			jsonName = f.Name
		}
		t, err := tsType(f.Type, declared, name)
		if err != nil {
			return fmt.Errorf("field %s: %w", f.Name, err)
		}
		mark := ""
		if strings.Contains(opts, "omitempty") || f.Type.Kind() == reflect.Pointer {
			mark = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", jsonName, mark, t)
	}
	fmt.Fprintln(b, "}")
	return nil
}

func tsType(t reflect.Type, declared map[string]bool, name func(reflect.Type) string) (string, error) {
	switch t.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Pointer:
		return tsType(t.Elem(), declared, name)
	case reflect.Slice, reflect.Array:
		elem, err := tsType(t.Elem(), declared, name)
		if err != nil {
			return "", err
		}
		return elem + "[]", nil
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("map key %s is not a string", t.Key())
		}
		val, err := tsType(t.Elem(), declared, name)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("Record<string, %s>", val), nil
	case reflect.Struct:
		n := name(t)
		if !declared[n] {
			return "", fmt.Errorf("%s is not flagged TS ahead of its use", n)
		}
		return n, nil
	default:
		return "", fmt.Errorf("no TypeScript form for Go type %s", t)
	}
}

// tsResult is written out, not derived: the union, the Error subclass
// and the try/catch helpers are TS idiom no Go struct carries.
const tsResult = `export class MagusError extends Error implements Diagnostic {
  readonly code: string;
  readonly url?: string;
  readonly fix?: string;

  constructor(d: Diagnostic, options?: ErrorOptions) {
    super(d.message, options);
    this.name = "MagusError";
    this.code = d.code;
    if (d.url !== undefined) this.url = d.url;
    if (d.fix !== undefined) this.fix = d.fix;
  }
}

export type Result<T, E extends Error = MagusError> =
  | { value: T; error?: undefined }
  | { value?: undefined; error: E };

export function ok<T>(value: T): Result<T, never> {
  return { value };
}

export function fail<E extends Error>(error: E): Result<never, E> {
  return { error };
}

export function attempt<T>(fn: () => T): Result<T> {
  try {
    return ok(fn());
  } catch (e) {
    return fail(toMagusError(e));
  }
}

export async function fromPromise<T>(p: Promise<T>): Promise<Result<T>> {
  try {
    return ok(await p);
  } catch (e) {
    return fail(toMagusError(e));
  }
}

export function parseJSON(text: string): Result<unknown> {
  return attempt((): unknown => JSON.parse(text));
}

function toMagusError(e: unknown): MagusError {
  if (e instanceof MagusError) return e;
  if (e instanceof ConnectError) {
    return new MagusError({ code: Code[e.code], message: e.rawMessage }, { cause: e });
  }
  const message = e instanceof Error ? e.message : String(e);
  return new MagusError({ code: "", message }, { cause: e });
}
`

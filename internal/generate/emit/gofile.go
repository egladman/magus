package emit

import (
	"bytes"
	"fmt"
	"strings"
)

// GoImport is one import line of a generated Go file. An empty Alias
// imports Path under its own name.
type GoImport struct {
	Alias string
	Path  string
}

// GoHeader starts a generated Go file whose generator is tool: the DO NOT
// EDIT line, the package clause and one import block. Each group is
// separated from the next by a blank line, the way gofmt keeps groups.
func GoHeader(tool, pkg string, groups ...[]GoImport) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by %s. DO NOT EDIT.\n\npackage %s\n\nimport (\n", tool, pkg)
	for i, group := range groups {
		if i > 0 {
			b.WriteString("\n")
		}
		for _, imp := range group {
			if imp.Alias == "" {
				fmt.Fprintf(&b, "\t%q\n", imp.Path)
				continue
			}
			fmt.Fprintf(&b, "\t%s %q\n", imp.Alias, imp.Path)
		}
	}
	b.WriteString(")\n\n")
	return b.Bytes()
}

// Directive reads the -name value flags of a `//go:generate` line that
// runs command, double quotes trimmed. ok is false for any other line.
func Directive(line, command string) (flags map[string]string, ok bool) {
	line = strings.TrimSpace(line)
	if !strings.HasPrefix(line, "//go:generate ") || !strings.Contains(line, command+" ") {
		return nil, false
	}
	flags = map[string]string{}
	fields := strings.Fields(line)
	for i := 0; i+1 < len(fields); i++ {
		if name, isFlag := strings.CutPrefix(fields[i], "-"); isFlag {
			flags[name] = strings.Trim(fields[i+1], `"`)
		}
	}
	return flags, true
}

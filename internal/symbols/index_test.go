// The bare scip op's index keeps the file every cached run already stamped, and a second
// indexing spell on the same project writes beside it rather than over it.
func TestIndexPathIsOnePerIndexerOp(t *testing.T) {
	cacheDir, dir := t.TempDir(), t.TempDir()
	goIndex := IndexPath(cacheDir, dir, "scip")
	buzzIndex := IndexPath(cacheDir, dir, "scip-buzz")

	assert.Equal(t, "index.scip", filepath.Base(goIndex))
	assert.Equal(t, "scip-buzz.scip", filepath.Base(buzzIndex))
	assert.Equal(t, filepath.Dir(goIndex), filepath.Dir(buzzIndex), "both live under the project's one cache dir")
}

func TestFingerprintBodies(t *testing.T) {
	root := t.TempDir()
	src := "package a\n\nfunc F() {\n\treturn\n}\n\nconst C = 1"
	require.NoError(t, os.MkdirAll(filepath.Join(root, "a"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, "a", "a.go"), []byte(src), 0o644))
	lines := types.SplitSourceLines([]byte(src))
	body, _ := types.BodyDigest(lines, 3, 5)
	decl, _ := types.BodyDigest(lines, 7, 7)

	syms := []types.KnowledgeSymbol{
		{Key: "F", Source: "a/a.go:3", DefEndLine: 5},
		{Key: "C", Source: "a/a.go:7"},
		{Key: "Gone", Source: "a/gone.go:1"},
		{Key: "Past", Source: "a/a.go:6", DefEndLine: 99},
		{Key: "RefOnly"},
	}
	FingerprintBodies(root, syms)

	assert.Equal(t, []types.KnowledgeSymbol{
		{Key: "F", Source: "a/a.go:3", DefEndLine: 5, BodyDigest: body, SourceLines: 7, SourceBytes: len(src)},
		{Key: "C", Source: "a/a.go:7", BodyDigest: decl, SourceLines: 7, SourceBytes: len(src)},
		{Key: "Gone", Source: "a/gone.go:1"},
		// The file was read, so it is sized, but the range overruns it: no digest.
		{Key: "Past", Source: "a/a.go:6", DefEndLine: 99, SourceLines: 7, SourceBytes: len(src)},
		{Key: "RefOnly"},
	}, syms)
}

// A file's generated-code header marks every symbol it defines, from the read that sizes it.
func TestFingerprintBodiesMarksGeneratedSource(t *testing.T) {
	root := t.TempDir()
	require.NoError(t, os.MkdirAll(filepath.Join(root, "a"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, "a", "made.go"), []byte("// Code generated by x. DO NOT EDIT.\n\npackage a\n\nconst M = 1\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(root, "a", "hand.go"), []byte("package a\n\nconst H = 1\n"), 0o644))

	syms := []types.KnowledgeSymbol{{Key: "M", Source: "a/made.go:5"}, {Key: "H", Source: "a/hand.go:3"}}
	FingerprintBodies(root, syms)

	assert.True(t, syms[0].SourceGenerated)
	assert.False(t, syms[1].SourceGenerated)
}

// Two copies that differ only in names and literal values share a shape, and a body that
// differs in structure does not. A language with no lexer gets no shape, and neither does a
// symbol with no body span.
func TestFingerprintBodiesShapesRenamedCopies(t *testing.T) {
	root := t.TempDir()
	src := "package a\n\n" +
		"func Sum(xs []int) int {\n\tn := 0\n\tfor _, x := range xs {\n\t\tn += x\n\t}\n\treturn n + 1\n}\n\n" +
		"// Total is Sum renamed.\nfunc Total(vals []int) int {\n\tacc := 0\n\tfor _, v := range vals {\n\t\tacc += v\n\t}\n\treturn acc + 2\n}\n\n" +
		"func Max(xs []int) int {\n\tn := 0\n\tfor _, x := range xs {\n\t\tn = max(n, x)\n\t}\n\treturn n\n}\n"
	require.NoError(t, os.MkdirAll(filepath.Join(root, "a"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, "a", "a.go"), []byte(src), 0o644))

	syms := []types.KnowledgeSymbol{
		{Key: "Sum", Language: "go", Source: "a/a.go:3", DefEndLine: 9},
		{Key: "Total", Language: "go", Source: "a/a.go:12", DefEndLine: 18},
		{Key: "Max", Language: "go", Source: "a/a.go:20", DefEndLine: 26},
		{Key: "Buzz", Language: "buzz", Source: "a/a.go:3", DefEndLine: 9},
		{Key: "NoSpan", Language: "go", Source: "a/a.go:3"},
	}
	FingerprintBodies(root, syms)

	sum, total, maxFn, buzz, noSpan := syms[0], syms[1], syms[2], syms[3], syms[4]
	require.NotEmpty(t, sum.BodyShape)
	assert.Equal(t, sum.BodyShape, total.BodyShape, "renamed copies share a shape")
	assert.Equal(t, sum.BodyTokens, total.BodyTokens)
	assert.Positive(t, sum.BodyTokens)
	assert.NotEqual(t, sum.BodyDigest, total.BodyDigest, "the text differs")
	assert.NotEqual(t, sum.BodyShape, maxFn.BodyShape, "a different body has a different shape")
	assert.Empty(t, buzz.BodyShape)
	assert.Zero(t, buzz.BodyTokens)
	assert.NotEmpty(t, buzz.BodyDigest, "a digest needs no lexer")
	assert.Empty(t, noSpan.BodyShape)
}

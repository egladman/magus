// GlueSource prefixes the asset source of every hook glue file the binary embeds, the
// copy docs/guides/integrations/agents generates into gen/glue. An asset loaded from it
// is installed stamped, see GlueAsset.
const GlueSource = "magus:glue/"

// glueFS holds the hook glue. It is the agent package's, not a spell's: no spell
// artifact publishes it, and a pulled spell installs the glue of the binary running it.
//
//go:embed gen/glue
var glueFS embed.FS

// GlueAsset reads the embedded glue a GlueSource names and stamps it.
func GlueAsset(source string) ([]byte, error) {
	name, ok := strings.CutPrefix(source, GlueSource)
	if !ok || !fs.ValidPath(name) {
		return nil, fmt.Errorf("%q names no embedded hook glue", source)
	}
	body, err := fs.ReadFile(glueFS, "gen/glue/"+name)
	if err != nil {
		return nil, err
	}
	return stampGlue(body), nil
}

// IsGlueScript reports whether name, a file name such as magus-command.buzz, is a hook
// script the binary embeds. lib/ is the module the scripts import, never a script.
//
// compat: see legacyGlueScript in cmd/magus/hook_glue.go.
func IsGlueScript(name string) bool {
	if name == "" || strings.Contains(name, "/") || !strings.HasSuffix(name, ".buzz") {
		return false
	}
	info, err := fs.Stat(glueFS, "gen/glue/"+name)
	return err == nil && !info.IsDir()
}

// WriteGlue writes every embedded glue file, unstamped, under dir, the scripts and
// lib/ beside them so their imports resolve. A file already holding its bytes is left.
//
// compat: see legacyGlueScript in cmd/magus/hook_glue.go.
func WriteGlue(dir string) error {
	return fs.WalkDir(glueFS, "gen/glue", func(name string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		body, err := fs.ReadFile(glueFS, name)
		if err != nil {
			return err
		}
		dest := filepath.Join(dir, filepath.FromSlash(strings.TrimPrefix(name, "gen/glue/")))
		if have, err := os.ReadFile(dest); err == nil && bytes.Equal(have, body) {
			return nil
		}
		if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
			return err
		}
		return file.WriteFileAtomic(dest, body, 0o644)
	})
}

// GlueDigest identifies the embedded glue as a whole, so two binaries shipping different
// glue never share a directory WriteGlue filled.
func GlueDigest() (string, error) {
	sum := sha256.New()
	err := fs.WalkDir(glueFS, "gen/glue", func(name string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		body, err := fs.ReadFile(glueFS, name)
		if err != nil {
			return err
		}
		fmt.Fprintf(sum, "%s\x00%d\x00", name, len(body))
		_, err = sum.Write(body)
		return err
	})
	return fmt.Sprintf("%x", sum.Sum(nil))[:12], err
}

// glueRemedy is the command every glue finding names: install rewrites a stamped copy
// whatever it holds.
const glueRemedy = "magus agent harness install"

const glueStampPrefix = "// generated by: magus agent harness install;"

var glueStampRe = regexp.MustCompile(`glue-version: (\d+); glue-content: ([0-9a-f]+);`)

// stampGlue returns body with the line that marks it as an installed copy appended: the
// glue version this binary ships (GuardTemplateVersion) and the digest of body. The digest
// is what tells an edited copy from one another magus installed, so it covers body alone.
func stampGlue(body []byte) []byte {
	stamped := bytes.Clone(body)
	if len(stamped) > 0 && stamped[len(stamped)-1] != '\n' {
		stamped = append(stamped, '\n')
	}
	return fmt.Appendf(stamped, "%s glue-version: %d; glue-content: %s; do not edit, re-run to update\n",
		glueStampPrefix, GuardTemplateVersion, glueDigest(body))
}

func glueDigest(body []byte) string { return assetDigest(body)[:12] }

// glueStamp is what an installed copy's stamp line says, and whether it had one.
type glueStamp struct {
	version int
	digest  string
	ok      bool
}

// readGlueStamp splits a copy into the body its stamp covers and the stamp. The stamp is
// the copy's last line, so text added after it reads as no stamp at all.
func readGlueStamp(body []byte) ([]byte, glueStamp) {
	at := bytes.LastIndex(body, []byte(glueStampPrefix))
	if at == -1 || bytes.IndexByte(body[at:], '\n') != len(body)-at-1 {
		return body, glueStamp{}
	}
	match := glueStampRe.FindSubmatch(body[at:])
	if match == nil {
		return body, glueStamp{}
	}
	version, err := strconv.Atoi(string(match[1]))
	if err != nil {
		return body, glueStamp{}
	}
	return body[:at], glueStamp{version: version, digest: string(match[2]), ok: true}
}

// carriesGlueStamp reports whether body is a copy install wrote, which install and the
// harness linker may replace whatever it holds: the stamp says not to edit it.
func carriesGlueStamp(body []byte) bool {
	_, stamp := readGlueStamp(body)
	return stamp.ok
}

// glueLinked reports whether the workspace links path to a file of its own, as a checkout
// of magus links its glue to the sources it edits. Install leaves a link alone.
func glueLinked(root, relative string) (bool, error) {
	info, err := os.Lstat(filepath.Join(root, relative))
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return false, nil
		}
		return false, err
	}
	return info.Mode()&os.ModeSymlink != 0, nil
}

// glueProblem says what is wrong with the installed copy of one glue asset, or "" when it
// is the binary's own or a link to an existing file. Missing, edited and installed by
// another magus are three findings with one remedy.
func glueProblem(root string, a HarnessRuntimeAsset) string {
	path := filepath.Join(root, a.Path)
	linked, err := glueLinked(root, a.Path)
	if err != nil {
		return fmt.Sprintf("hook glue %s cannot be read: %v", a.Path, err)
	}
	body, err := os.ReadFile(path)
	switch {
	case errors.Is(err, fs.ErrNotExist) && linked:
		return glueFinding("hook glue %s links to a file that does not exist", a.Path)
	case errors.Is(err, fs.ErrNotExist):
		return glueFinding("hook glue %s is missing, so every hook that runs it fails closed", a.Path)
	case err != nil:
		return fmt.Sprintf("hook glue %s cannot be read: %v", a.Path, err)
	case linked || bytes.Equal(body, a.Content):
		return ""
	}
	rest, have := readGlueStamp(body)
	_, want := readGlueStamp(a.Content)
	switch {
	case !have.ok || glueDigest(rest) != have.digest:
		return glueFinding("hook glue %s was edited after install, so it is not the glue this magus ships", a.Path)
	case have.version != want.version:
		return glueFinding("hook glue %s is glue version %d, and this magus ships version %d", a.Path, have.version, want.version)
	default:
		return glueFinding("hook glue %s was installed by another magus build (glue-content %s, and this magus ships %s)", a.Path, have.digest, want.digest)
	}
}

func glueFinding(format string, args ...any) string {
	return fmt.Sprintf("%s; run `%s`", fmt.Sprintf(format, args...), glueRemedy)
}

// legacyGlueLines is each path under docs/guides/integrations/agents to a script the
// binary embeds that a hook command in config runs: where every line named its glue
// before install copied it. An opt-in script magus does not install, such as
// proofread-reply.buzz, stays wired there and is not listed.
//
// compat: see legacyGlueScript in cmd/magus/hook_glue.go.
func legacyGlueLines(config map[string]any) []string {
	var commands, found []string
	collectCommands(config, &commands)
	for _, command := range commands {
		for _, word := range strings.Fields(command) {
			name, legacy := strings.CutPrefix(word, "docs/guides/integrations/agents/")
			if legacy && IsGlueScript(name) && !slices.Contains(found, word) {
				found = append(found, word)
			}
		}
	}
	return found
}

// glueProblems is every finding over d's glue assets, in the order d declares them.
func glueProblems(root string, d HarnessDescriptor) []string {
	var problems []string
	for _, a := range d.Assets {
		if !a.Glue {
			continue
		}
		if problem := glueProblem(root, a); problem != "" {
			problems = append(problems, problem)
		}
	}
	return problems
}

// IsGlueSource reports whether an asset source names embedded hook glue.
func IsGlueSource(source string) bool { return strings.HasPrefix(source, GlueSource) }

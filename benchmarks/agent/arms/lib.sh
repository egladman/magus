# shellcheck shell=sh
# Helpers shared by every arm's provision.sh and probe.sh.
#
# An arm is a provisioning recipe applied to a fresh worktree of the fixture
# repo, plus a probe that proves the worktree is in that arm. Both take the
# worktree as their first argument; provision also takes the magus binary, so
# one recipe can pin two different builds of magus for an A/B of magus itself.

arm_die() {
    printf 'arm %s: FAILED: %s\n' "${ARM_NAME:-?}" "$*" >&2
    exit 1
}

# arm_worktree validates the fixture worktree argument and prints its absolute
# path. A magus.yaml is what makes the directory a workspace root; provisioning
# a directory without one would produce an arm nothing can run in.
arm_worktree() {
    [ -n "$1" ] || arm_die "usage: $0 <worktree> [magus-binary]"
    [ -d "$1" ] || arm_die "worktree $1 does not exist"
    [ -f "$1/magus.yaml" ] || arm_die "worktree $1 has no magus.yaml, so it is not a magus workspace"
    (cd "$1" && pwd)
}

# arm_binary validates the magus binary argument and prints its absolute path.
arm_binary() {
    [ -n "$1" ] || arm_die "usage: $0 <worktree> <magus-binary>"
    [ -x "$1" ] || arm_die "magus binary $1 is not executable"
    printf '%s/%s\n' "$(cd "$(dirname "$1")" && pwd)" "$(basename "$1")"
}

# arm_templates prints the directory holding the shipped guard hook templates,
# resolved from this checkout rather than from the binary: the binary is pinned
# separately, and doctor's guard-wiring check fails loudly when the two disagree.
arm_templates() {
    printf '%s\n' "$(cd "$(dirname "$0")/../../../../docs/guides/integrations/agents" && pwd)"
}

# arm_reset clears everything an arm owns, so provisioning twice lands in the
# same state as provisioning once.
arm_reset() {
    rm -rf "$1/.benchmark" "$1/.claude" "$1/MAGUS.md" "$1/CLAUDE.md" "$1/.mcp.json"
    mkdir -p "$1/.benchmark/claude-config" "$1/.benchmark/home" "$1/.claude"
}

# arm_write_env writes the file the runner sources after scrubbing the
# environment. Arm-specific exports are read from stdin and appended.
#
# CLAUDE_CONFIG_DIR moves the host's user-scoped config, MCP registrations
# included, into the run's own empty directory; see README.md.
# Activity-trail rotation is disabled (a non-positive interval schedules no
# job), so a run's own trail survives to be harvested.
arm_write_env() {
    wt=$1
    bin=$2
    {
        printf '# generated by benchmarks/agent/arms/%s/provision.sh; the runner sources this file.\n' "$ARM_NAME"
        # shellcheck disable=SC2016  # $PATH expands when the runner sources env.sh
        printf 'PATH="%s:$PATH"; export PATH\n' "$(dirname "$bin")"
        printf 'BENCH_MAGUS_BIN="%s"; export BENCH_MAGUS_BIN\n' "$bin"
        printf 'CLAUDE_CONFIG_DIR="%s/.benchmark/claude-config"; export CLAUDE_CONFIG_DIR\n' "$wt"
        printf 'MAGUS_DAEMON_MAINTENANCE_ROTATE_ACTIVITIES=0; export MAGUS_DAEMON_MAINTENANCE_ROTATE_ACTIVITIES\n'
        cat
    } > "$wt/.benchmark/env.sh"
}

# arm_load_env sources the run environment and checks the parts every arm
# shares. Probes call it first: an arm whose binary is not the one on PATH is
# measuring a different magus than the one it was handed.
arm_load_env() {
    [ -f "$1/.benchmark/env.sh" ] || arm_die "no .benchmark/env.sh, so the runner has no environment to source"
    # shellcheck disable=SC1091  # generated at provision time
    . "$1/.benchmark/env.sh"
    [ -n "$BENCH_MAGUS_BIN" ] || arm_die "env.sh exports no BENCH_MAGUS_BIN"
    [ -x "$BENCH_MAGUS_BIN" ] || arm_die "BENCH_MAGUS_BIN=$BENCH_MAGUS_BIN is not executable"
    resolved=$(command -v magus 2>/dev/null)
    [ "$resolved" = "$BENCH_MAGUS_BIN" ] || arm_die "PATH resolves magus to ${resolved:-nothing}, not $BENCH_MAGUS_BIN"
    [ "$MAGUS_DAEMON_MAINTENANCE_ROTATE_ACTIVITIES" = "0" ] || arm_die "activity-trail rotation is not pinned off (MAGUS_DAEMON_MAINTENANCE_ROTATE_ACTIVITIES=${MAGUS_DAEMON_MAINTENANCE_ROTATE_ACTIVITIES:-unset})"
    [ -d "$CLAUDE_CONFIG_DIR" ] || arm_die "CLAUDE_CONFIG_DIR=${CLAUDE_CONFIG_DIR:-unset} is not a directory"
}

# arm_check_no_mcp proves no MCP server is reachable from the worktree: none
# registered in the run's own config dir, and none declared by the tree itself.
arm_check_no_mcp() {
    [ ! -e "$1/.mcp.json" ] || arm_die ".mcp.json exists, so the tree registers project-scoped MCP servers"
    command -v claude >/dev/null 2>&1 || arm_die "claude is not on PATH, so MCP absence cannot be proven"
    servers=$(cd "$1" && claude mcp list 2>&1) || true
    case $servers in
    *"No MCP servers configured"*) ;;
    *) arm_die "claude mcp list reports servers under CLAUDE_CONFIG_DIR=$CLAUDE_CONFIG_DIR: $servers" ;;
    esac
}

# arm_doctor runs doctor against the worktree and prints its JSON. HOME points
# at the run's own empty home so that home-scoped hook configs on the machine
# running the benchmark cannot decide an arm's verdict; doctor reads $HOME for
# its guard-wiring and checkpoint-wiring candidates.
#
# Exit status is ignored: checks unrelated to the arm (an unreachable VCS base
# ref in a throwaway fixture, say) fail without saying anything about the arm.
arm_doctor() {
    HOME="$1/.benchmark/home" "$BENCH_MAGUS_BIN" --root "$1" doctor -o json 2>/dev/null
}

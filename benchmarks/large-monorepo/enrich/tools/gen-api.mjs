#!/usr/bin/env node
// Writes each package's gen/api.md: the names it exports and the sibling packages
// it imports from. Stdlib-only and free of timestamps so a task worktree with no
// node_modules can regenerate it byte-for-byte and --check is a real drift gate.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SKIP_DIRS = new Set(['node_modules', 'gen', '.next', '.git', '.turbo', '.nx']);

function projectDirs() {
  const dirs = [];
  for (const group of ['apps', 'packages']) {
    const groupDir = join(ROOT, group);
    if (!existsSync(groupDir)) continue;
    for (const entry of readdirSync(groupDir).sort()) {
      const candidate = join(groupDir, entry);
      if (!statSync(candidate).isDirectory()) continue;
      if (existsSync(join(candidate, 'package.json'))) {
        dirs.push(candidate);
        continue;
      }
      for (const nested of readdirSync(candidate).sort()) {
        const nestedDir = join(candidate, nested);
        if (statSync(nestedDir).isDirectory() && existsSync(join(nestedDir, 'package.json'))) {
          dirs.push(nestedDir);
        }
      }
    }
  }
  return dirs;
}

function moduleFiles(dir) {
  const found = [];
  const walk = (current) => {
    for (const entry of readdirSync(current).sort()) {
      if (SKIP_DIRS.has(entry)) continue;
      const path = join(current, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (entry.endsWith('.mjs') && !entry.endsWith('.test.mjs')) found.push(path);
    }
  };
  walk(dir);
  return found;
}

function exportedNames(source) {
  const names = [];
  for (const m of source.matchAll(/^export\s+(?:async\s+)?(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm)) {
    names.push(m[1]);
  }
  for (const m of source.matchAll(/^export\s*\{([^}]*)\}/gm)) {
    for (const part of m[1].split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop();
      if (name) names.push(name.trim());
    }
  }
  return names;
}

// A relative specifier that resolves outside this project names a dependency; the
// owning project is the nearest ancestor of the target that carries a package.json.
function dependencyOf(fromFile, specifier, projectDir) {
  if (!specifier.startsWith('.')) return null;
  const target = resolve(dirname(fromFile), specifier);
  if (!relative(projectDir, target).startsWith('..')) return null;
  let owner = dirname(target);
  while (owner.startsWith(ROOT) && owner !== ROOT) {
    if (existsSync(join(owner, 'package.json'))) return relative(ROOT, owner).split(sep).join('/');
    owner = dirname(owner);
  }
  return null;
}

function render(projectDir) {
  const name = JSON.parse(readFileSync(join(projectDir, 'package.json'), 'utf8')).name;
  const exports = new Set();
  const deps = new Map();
  for (const file of moduleFiles(projectDir)) {
    const source = readFileSync(file, 'utf8');
    for (const n of exportedNames(source)) exports.add(n);
    for (const m of source.matchAll(/\bimport\s+(?:\{([^}]*)\}\s+from\s+)?'([^']+)'/g)) {
      const dep = dependencyOf(file, m[2], projectDir);
      if (!dep) continue;
      if (!deps.has(dep)) deps.set(dep, new Set());
      for (const part of (m[1] ?? '').split(',')) {
        const imported = part.trim().split(/\s+as\s+/)[0].trim();
        if (imported) deps.get(dep).add(imported);
      }
    }
  }
  const lines = [`# ${name} API`, '', 'Generated by tools/gen-api.mjs. Do not edit by hand.', '', '## Exports', ''];
  lines.push(...(exports.size ? [...exports].sort().map((n) => `- ${n}`) : ['- (none)']));
  lines.push('', '## Depends on', '');
  const depLines = [...deps.keys()].sort().map((dep) => {
    const names = [...deps.get(dep)].sort();
    return names.length ? `- ${dep} (${names.join(', ')})` : `- ${dep}`;
  });
  lines.push(...(depLines.length ? depLines : ['- (none)']));
  return `${lines.join('\n')}\n`;
}

function apiPath(projectDir) {
  return join(projectDir, 'gen', 'api.md');
}

function write(projectDir) {
  mkdirSync(join(projectDir, 'gen'), { recursive: true });
  writeFileSync(apiPath(projectDir), render(projectDir));
}

function check(projectDir) {
  const path = apiPath(projectDir);
  const want = render(projectDir);
  if (!existsSync(path)) return `missing ${relative(ROOT, path)}`;
  if (readFileSync(path, 'utf8') !== want) return `stale ${relative(ROOT, path)}`;
  return null;
}

function main(argv) {
  const mode = argv[0];
  const explicit = argv[1] ? [resolve(argv[1])] : null;
  const targets = (explicit ?? projectDirs()).filter((dir) => moduleFiles(dir).length > 0);
  if (mode === '--write') {
    for (const dir of targets) write(dir);
    return 0;
  }
  if (mode === '--check') {
    const problems = targets.map(check).filter(Boolean);
    for (const problem of problems) console.error(`api summary out of date: ${problem}`);
    if (problems.length) console.error('run: node tools/gen-api.mjs --write');
    return problems.length ? 1 : 0;
  }
  console.error('usage: gen-api.mjs --write|--check [projectDir]');
  return 2;
}

process.exit(main(process.argv.slice(2)));

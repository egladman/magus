// outFile is the destination from the REPO ROOT, which is where a bare
// `go run ./cmd/langservice-manifest` starts. go:generate runs in the package dir
// instead, so it passes -out; the drift test reads this path to find the committed
// file whichever route wrote it.
const outFile = "internal/langservice/manifest_data.go"

func main() {
	var out string
	command.Main(command.Command{
		Name:  "langservice-manifest",
		Short: "Regenerate the host module snapshot the playground's completion and hover read.",
		Flags: []command.Flag{{Name: "out", Kind: command.String, Default: outFile, Doc: "destination for the generated manifest", Target: &out}},
		Run: func(_ context.Context, inv command.Invocation) error {
			return run(out, inv.Stdout)
		},
	})
}

func run(out string, log io.Writer) error {
	src, emitted, err := render()
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.FromSlash(out), src, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", out, err)
	}
	fmt.Fprintf(log, "wrote %s (%d modules)\n", out, emitted)
	return nil
}

// render builds the manifest source without writing it, so a drift test can compare
// it against the committed file. The generator and that gate read the same function, so
// a module added without regenerating fails the test instead of leaving completion and
// hover unaware of it.
func render() (src []byte, emitted int, err error) {
	list := append(hostmodules.All(), std.SourceModulesAsModules()...)
	slices.SortFunc(list, func(a, b std.Module) int { return strings.Compare(a.Name, b.Name) })

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/langservice-manifest; DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: magus run generate\n\n")
	b.WriteString("package langservice\n\n")
	b.WriteString("// modules is the snapshot of the magus host module API used by completion\n")
	b.WriteString("// and hover. See cmd/langservice-manifest.\n")
	b.WriteString("var modules = []Module{\n")

	for _, mod := range list {
		signatures, err := declaredSignatures(mod.Name)
		if err != nil {
			return nil, 0, fmt.Errorf("module %s: %w", mod.Name, err)
		}
		fmt.Fprintf(&b, "\t{\n\t\tName: %q,\n\t\tDoc: %q,\n", mod.Name, mod.Doc)

		if len(mod.Fields) > 0 {
			b.WriteString("\t\tFields: []Field{\n")
			for _, f := range mod.Fields {
				fmt.Fprintf(&b, "\t\t\t{Name: %q, Type: %q, Doc: %q},\n", f.Name, f.Type.GoType(), f.Doc)
			}
			b.WriteString("\t\t},\n")
		}
		if len(mod.Methods) > 0 {
			b.WriteString("\t\tMethods: []Method{\n")
			for _, meth := range mod.Methods {
				name := std.BuzzMethodName(meth)
				sig, ok := signatures[name]
				if !ok {
					return nil, 0, fmt.Errorf("%s\\%s has no exported declaration", mod.Name, name)
				}
				if sig == "" {
					// Buzz exports variadics as untyped values.
					sig = std.BuzzSignature(mod, meth)
				}
				fmt.Fprintf(&b, "\t\t\t{Name: %q, Doc: %q, Sig: %q},\n", name, meth.Doc, sig)
			}
			b.WriteString("\t\t},\n")
		}
		b.WriteString("\t},\n")
		emitted++
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, 0, fmt.Errorf("gofmt generated source: %w", err)
	}
	return out, emitted, nil
}

// Source spans retain the defaults and error sets the compiler reads.
func declaredSignatures(module string) (map[string]string, error) {
	src, ok := spell.ModuleDecls(module)
	if !ok {
		sm, found := std.GetSource(module)
		if !found {
			return nil, fmt.Errorf("no declaration source")
		}
		src = sm.Source
	}
	program, err := buzz.ParseEmbedded(src)
	if err != nil {
		return nil, err
	}
	starts := []int{0}
	for i, c := range src {
		if c == '\n' {
			starts = append(starts, i+1)
		}
	}
	offset := func(p ast.Pos) int { return starts[p.Line-1] + p.Col - 1 }
	sigs := make(map[string]string)
	for _, stmt := range program.Stmts {
		switch decl := stmt.(type) {
		case *ast.FunDecl:
			if !decl.IsExported {
				continue
			}
			start := offset(decl.Pos)
			var header string
			if decl.IsExtern {
				// moduledecls emits one extern per line, ending in a semicolon.
				line, _, _ := strings.Cut(src[start:], "\n")
				header = strings.TrimSuffix(strings.TrimPrefix(line, "extern fun "), ";")
			} else {
				header = strings.TrimSpace(strings.TrimPrefix(src[start:offset(decl.Body.Pos)], "fun "))
			}
			sigs[decl.Name] = fmt.Sprintf("%s\\%s", module, header)
		case *ast.DeclStmt:
			if decl.IsExported && decl.TypeAnnot == "any" {
				sigs[decl.Name] = ""
			}
		}
	}
	return sigs, nil
}

package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"sort"

	"github.com/egladman/magus/internal/generate/emit"
)

// runBoundaryList emits the list of runtime boundary types, so a test can iterate every
// value that crosses Go -> Buzz instead of naming them by hand.
//
// A hand-maintained list is the failure this prevents. types.DoctorCheckStatus crossed
// as null for an unknown stretch because a type switch matches on identity and no test
// covered every boundary type - and the same trap had already bitten types.BuzzObject
// once. Sourcing the list from the registry that generates the mirrors means a new
// boundary type is covered the moment it is declared.
func runBoundaryList(args []string) error {
	fs := flag.NewFlagSet("boundarylist", flag.ExitOnError)
	outPath := fs.String("out", "", "output Go file path")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *outPath == "" {
		return fmt.Errorf("usage: magus-utils boundarylist -out <path.go>")
	}

	var names []string
	for _, e := range boundaryTypes {
		if !e.RuntimeObject {
			continue
		}
		t := e.Type
		names = append(names, t.PkgPath()[len("github.com/egladman/magus/"):]+"."+t.Name())
	}
	sort.Strings(names)

	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by magus-utils boundarylist. DO NOT EDIT.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package gen")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, `import "github.com/egladman/magus/types"`)
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "// RuntimeBoundaryTypes is every value magus encodes for Buzz, zero-valued. A test")
	fmt.Fprintln(&b, "// populates each and asserts the round trip loses nothing.")
	fmt.Fprintln(&b, "var RuntimeBoundaryTypes = []any{")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%s{},\n", n)
	}
	fmt.Fprintln(&b, "}")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format boundary list: %w", err)
	}
	return emit.File(*outPath, formatted)
}

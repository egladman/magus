package main

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestRunBoundaryObjects(t *testing.T) {
	args := func(out string) []string { return []string{"-out", out} }

	got := readGenerated(t, runBoundaryObjects, args)
	assert.Contains(t, got, "Code generated by magus-utils boundaryobjects. DO NOT EDIT.")
	assert.Contains(t, got, "package gen")
	assert.Contains(t, got, "func ObjectExecResult(")
	// A type no DECLARED method returns: magus\job is bound by hand, so the registry
	// is the only route to its encoder. This is the case the whole generator exists for.
	assert.Contains(t, got, "func ObjectJob(")

	assertDeterministic(t, runBoundaryObjects, args)

	t.Run("no -out", func(t *testing.T) {
		err := runBoundaryObjects(nil)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "usage:")
	})
}

package main

import (
	"bytes"
	"context"
	"fmt"
	"go/format"
	"sort"

	"github.com/egladman/magus/internal/generate/emit"
	"github.com/egladman/magus/libs/clikit/command"
	"github.com/egladman/magus/libs/clikit/exit"
)

// boundaryListCommand emits the list of runtime boundary types, so a test can iterate every
// value that crosses Go -> Buzz instead of naming them by hand.
//
// A hand-maintained list is the failure this prevents. types.CheckStatus crossed
// as null for an unknown stretch because a type switch matches on identity and no test
// covered every boundary type, and the same trap had already bitten types.BuzzObject
// once. Sourcing the list from the registry that generates the mirrors means a new
// boundary type is covered the moment it is declared.
func boundaryListCommand() command.Command {
	var outPath, pkg string
	var rows []string
	return command.Command{
		Name:  "boundarylist",
		Short: "Generate the list of runtime boundary types",
		Flags: []command.Flag{
			{Name: "out", Kind: command.String, Doc: "output Go file path", Target: &outPath},
			{Name: "pkg", Kind: command.String, Doc: "package clause of the generated file", Target: &pkg},
		},
		Run: func(context.Context, command.Invocation) error {
			if outPath == "" || pkg == "" {
				return exit.Usagef("usage: magus-utils boundarylist -out <path.go> -pkg <package>")
			}

			used := map[string]bool{"types": true}
			objects := newBuzzValueEmitter()
			for _, e := range boundaryTypes() {
				if !e.Outbound {
					continue
				}
				t := e.Type
				qualified := qualifyType(t)
				used[typePackage(t).alias] = true
				// The encoder is named after the Go type, matching buzzValueEmitter.funcName.
				// Carried as a closure rather than left for the test to look up: a method could
				// be reached through an interface assertion, and a free function cannot.
				rows = append(rows, fmt.Sprintf("\t{Name: %q, Zero: %s{}, Encode: func(v any, enums ffi.EnumCases) vm.Value { return %s }},",
					e.Name, qualified, objects.call(t, fmt.Sprintf("v.(%s)", qualified))))
			}
			sort.Strings(rows)

			var b bytes.Buffer
			fmt.Fprintln(&b, "// Code generated by magus-utils boundarylist. DO NOT EDIT.")
			fmt.Fprintln(&b)
			fmt.Fprintln(&b, "package "+pkg)
			fmt.Fprintln(&b)
			fmt.Fprintln(&b, `import (`)
			fmt.Fprintln(&b, `	"github.com/egladman/magus/internal/interp/bindings/ffi"`)
			fmt.Fprintln(&b, `	vm "github.com/egladman/magus/libs/gopherbuzz/vm"`)
			b.WriteString(importLines(used))
			fmt.Fprintln(&b, `)`)
			fmt.Fprintln(&b)
			fmt.Fprintln(&b, "// RuntimeBoundaryTypes is every value magus encodes for Buzz, zero-valued and paired")
			fmt.Fprintln(&b, "// with its encoder. A test populates each and asserts the round trip loses nothing.")
			fmt.Fprintln(&b, "var RuntimeBoundaryTypes = []ffi.BoundaryType{")
			for _, r := range rows {
				fmt.Fprintln(&b, r)
			}
			fmt.Fprintln(&b, "}")

			formatted, err := format.Source(b.Bytes())
			if err != nil {
				return fmt.Errorf("format boundary list: %w", err)
			}
			return emit.File(outPath, formatted)
		},
	}
}

func writeModuleDecls(outDir string) error {
	if outDir == "" {
		return fmt.Errorf("usage: magus-utils moduledecls -outdir <dir>")
	}

	mods := hostmodules.All()
	slices.SortFunc(mods, func(a, b std.Module) int { return strings.Compare(a.Name, b.Name) })
	for _, mod := range mods {
		src, err := renderModuleDecls(mod)
		if err != nil {
			return fmt.Errorf("module %s: %w", mod.Name, err)
		}
		var b bytes.Buffer
		fmt.Fprintln(&b, "// Code generated by magus-utils moduledecls. DO NOT EDIT.")
		b.WriteString(docComment(mod.Doc))
		fmt.Fprintln(&b, "//")
		fmt.Fprintf(&b, "// Buzz declarations for the %s host module: the object mirrors its methods\n", mod.Name)
		fmt.Fprintln(&b, "// return, then one `export extern fun` per method. Registered with SetModuleDecls")
		fmt.Fprintln(&b, "// beside the native implementation, so the checker reads the signature while the")
		fmt.Fprintln(&b, "// runtime keeps the host binding - an extern emits no code, so it cannot shadow")
		fmt.Fprintln(&b, "// one. Edit the std.Module declaration and rerun `go generate`, never this file.")
		fmt.Fprintln(&b)
		b.WriteString(namespaceImports(mod.Name, src))
		b.WriteString(src)
		// Parse what we are about to write. A declaration source that does not parse is
		// not a loud failure at run time (SetModuleDecls drops it and the module simply
		// goes back to being untyped), so without this check a typo silently un-types a
		// whole module and every call through it stops being verified. That is exactly
		// how KnowledgeGodNode shipped an unparsable `in:` field: nothing parsed it.
		// Codegen is the right place to fail, for the same reason checkObjectDecls fails
		// here rather than at load.
		prog, err := buzz.Parse(b.String())
		if err != nil {
			return fmt.Errorf("generated declarations for %s do not parse: %w", mod.Name, err)
		}
		if missing := undeclaredTypeNames(prog); len(missing) > 0 {
			return fmt.Errorf("generated declarations for %s name undeclared types: %s", mod.Name, strings.Join(missing, ", "))
		}
		if err := emit.File(filepath.Join(outDir, mod.Name+".buzz"), b.Bytes()); err != nil {
			return fmt.Errorf("write %s: %w", mod.Name, err)
		}
	}
	for _, module := range nestedModules() {
		if err := writeNamespaceDecls(outDir, module); err != nil {
			return fmt.Errorf("namespace %s: %w", module, err)
		}
	}
	return nil
}

// writeNamespaceDecls writes the declaration file of the nested namespace at
// import path module: its enums and mirrors, under its `namespace` line.
func writeNamespaceDecls(outDir, module string) error {
	src, err := namespaceDeclSource(module)
	if err != nil {
		return err
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by magus-utils moduledecls. DO NOT EDIT.")
	fmt.Fprintln(&b, "//")
	fmt.Fprintf(&b, "// Buzz declarations for the %s namespace: the mirrors of the Go package\n", strings.ReplaceAll(module, "/", `\`))
	fmt.Fprintf(&b, "// it derives from. A script names them after `import %q;`. Edit the\n", module)
	fmt.Fprintln(&b, "// Go types and rerun `go generate`, never this file.")
	fmt.Fprintln(&b)
	b.WriteString(src)
	prog, err := buzz.Parse(b.String())
	if err != nil {
		return fmt.Errorf("generated declarations do not parse: %w", err)
	}
	if missing := undeclaredTypeNames(prog); len(missing) > 0 {
		return fmt.Errorf("generated declarations name undeclared types: %s", strings.Join(missing, ", "))
	}
	path := filepath.Join(outDir, module+".buzz")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return emit.File(path, b.Bytes())
}

// namespaceDeclSource is the declaration source of the nested namespace at
// module: its `namespace` line, its imports, then its enums and mirrors.
func namespaceDeclSource(module string) (string, error) {
	src, err := renderNamespaceDecls(module)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("namespace %s;\n\n%s%s", strings.ReplaceAll(module, "/", `\`), namespaceImports(module, src), src), nil
}

// renderNamespaceDecls renders the enums and mirrors declared in the nested
// namespace at module, leaf-first.
func renderNamespaceDecls(module string) (string, error) {
	mod := std.Module{Name: module}
	for _, entry := range boundaryTypes() {
		if entry.Module == module {
			mod.CallbackObjects = append(mod.CallbackObjects, entry.Name)
		}
	}
	return renderRecordDecls(mod)
}

// namespaceImports is the import line of each nested namespace other than
// module's own that src names a type of.
func namespaceImports(module, src string) string {
	var b strings.Builder
	if strings.Contains(src, `result\Result::<`) {
		b.WriteString("import \"result\";\n")
	}
	for _, nested := range nestedModules() {
		if nested != module && strings.Contains(src, qualifiedName(nested, "")) {
			fmt.Fprintf(&b, "import %q;\n", nested)
		}
	}
	if b.Len() > 0 {
		b.WriteByte('\n')
	}
	return b.String()
}

// renderModuleDecls renders one module's declaration source: the object mirrors its
// returns reference (leaf-first, since a field referencing an object needs that
// object declared already), then an extern per method.
func renderModuleDecls(mod std.Module) (string, error) {
	mod = mod.WithTags()
	records, err := renderRecordDecls(mod)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(records)
	for _, m := range sortedMethods(mod) {
		decl, err := documentedExternDecl(mod, m)
		if err != nil {
			return "", fmt.Errorf("%s: %w", m.Name, err)
		}
		b.WriteString(decl)
	}
	for _, p := range sortedProtocols(mod) {
		if p.Doc != "" {
			fmt.Fprintf(&b, "// %s\n", p.Doc)
		}
		fmt.Fprintf(&b, "export protocol %s {\n", p.Name)
		methods := slices.Clone(p.Methods)
		slices.SortFunc(methods, func(a, c std.Method) int { return strings.Compare(a.Name, c.Name) })
		for _, m := range methods {
			sig, err := protocolMethodSig(m)
			if err != nil {
				return "", fmt.Errorf("protocol %s: %s: %w", p.Name, m.Name, err)
			}
			fmt.Fprintf(&b, "    %s\n", sig)
		}
		b.WriteString("}\n\n")
	}
	// A Namespace renders as an OBJECT whose members are static extern methods:
	// `magus\cache.remote(...)` is member access on a value. An object
	// reports an unknown member, where a bare value could not.
	for _, ns := range mod.Namespaces {
		if ns.Doc != "" {
			fmt.Fprintf(&b, "// %s\n", ns.Doc)
		}
		fmt.Fprintf(&b, "export object %s {\n", ns.Name)
		for _, m := range sortedNamespaceMethods(ns) {
			decl, err := documentedExternDecl(mod, m)
			if err != nil {
				return "", fmt.Errorf("namespace %s: %s: %w", ns.Name, m.Name, err)
			}
			for line := range strings.SplitSeq(strings.TrimRight(decl, "\n"), "\n") {
				if strings.HasPrefix(line, "//") {
					fmt.Fprintf(&b, "    %s\n", line)
					continue
				}
				// externDecl renders a TOP-LEVEL declaration, which carries `export`.
				// Inside an object there is no export modifier (membership is what makes
				// it reachable), so drop it and mark the method static instead.
				fmt.Fprintf(&b, "    static %s\n", strings.TrimPrefix(line, "export "))
			}
		}
		b.WriteString("}\n\n")
	}
	return b.String(), nil
}

// renderRecordDecls renders the enums and object mirrors of one module's declarations,
// the part a session executes so a script can construct them.
func renderRecordDecls(mod std.Module) (string, error) {
	mod = mod.WithTags()
	var b strings.Builder
	mirrors, err := collectMirrors(mod)
	if err != nil {
		return "", err
	}
	// Enums first: an object mirror may use one as a field type, and Buzz needs the
	// declaration before the use.
	enums, err := collectEnums(mod, mirrors)
	if err != nil {
		return "", err
	}
	for _, e := range enums {
		b.Write(emit.BuzzEnum(e.Name, e.Closed, e.Cases))
		b.WriteByte('\n')
	}
	for _, name := range mirrors {
		entry, _ := boundaryTypeIn(mod.Name, name) // collectMirrors already resolved every name it returns
		out, err := renderBuzzMirrorDeclIn(mod.Name, name, entry.Type)
		if err != nil {
			return "", err
		}
		if o, ok := mirrorObject(mod, entry.Type); ok {
			if out, err = withObjectMethods(out, mod, o); err != nil {
				return "", err
			}
		}
		b.Write(out)
		b.WriteByte('\n')
	}
	externs, err := objectExternDecls(mod)
	if err != nil {
		return "", err
	}
	b.WriteString(externs)
	return b.String(), nil
}

// withObjectMethods inserts o's forwarding methods before the mirror's
// closing brace.
func withObjectMethods(mirror []byte, mod std.Module, o std.Object) ([]byte, error) {
	closing := bytes.LastIndex(mirror, []byte("}"))
	if closing < 0 {
		return nil, fmt.Errorf("mirror %s: no closing brace to declare its methods before", o.Name)
	}
	var methods bytes.Buffer
	for _, meth := range o.Methods {
		src, err := forwardingMethod(mod, o, meth)
		if err != nil {
			return nil, fmt.Errorf("object %s: %s: %w", o.Name, meth.Name, err)
		}
		methods.WriteString(src)
	}
	return slices.Concat(mirror[:closing], methods.Bytes(), mirror[closing:]), nil
}

// forwardingMethod renders meth as a Buzz method that passes `this` and its
// arguments, labeled, to the private extern mod.ObjectExtern declares.
func forwardingMethod(mod std.Module, o std.Object, meth std.Method) (string, error) {
	decl, err := externDecl(meth)
	if err != nil {
		return "", err
	}
	sig, isFun := strings.CutPrefix(strings.TrimSuffix(decl, ";\n"), "export extern ")
	if !isFun {
		return "", fmt.Errorf("a variadic argument cannot cross as a record method")
	}
	call := []string{"this"}
	for _, a := range meth.Args {
		call = append(call, fmt.Sprintf("%s: %s", a.Name, a.Name))
	}
	stmt := fmt.Sprintf("%s(%s);", mod.ObjectExtern(o, meth).Name, strings.Join(call, ", "))
	if len(meth.Returns) > 0 {
		stmt = "return " + stmt
	}
	return fmt.Sprintf("\n    %s {\n        %s\n    }\n", sig, stmt), nil
}

// objectExternDecls declares the private extern behind every object method.
// It carries no export: only the module's own forwarding methods call it.
func objectExternDecls(mod std.Module) (string, error) {
	var b strings.Builder
	for _, m := range mod.ObjectExterns() {
		decl, err := externDecl(m)
		if err != nil {
			return "", fmt.Errorf("%s: %w", m.Name, err)
		}
		b.WriteString(strings.TrimPrefix(decl, "export "))
	}
	if b.Len() > 0 {
		b.WriteByte('\n')
	}
	return b.String(), nil
}

// sortedNamespaceMethods orders a namespace's methods by name, so the generated
// declaration is byte-stable regardless of declaration order.
func sortedNamespaceMethods(ns std.Namespace) []std.Method {
	out := slices.Clone(ns.Methods)
	slices.SortFunc(out, func(a, b std.Method) int { return strings.Compare(a.Name, b.Name) })
	return out
}

// sortedProtocols orders a module's protocols by name for stable generated output.
func sortedProtocols(mod std.Module) []std.Protocol {
	out := slices.Clone(mod.Protocols)
	slices.SortFunc(out, func(a, b std.Protocol) int { return strings.Compare(a.Name, b.Name) })
	return out
}

// protocolMethodSig renders one protocol method as `fun name(params) > ret[!> any];`.
// Same shape as externDecl's parameter list, without the export-extern wrapper.
func protocolMethodSig(m std.Method) (string, error) {
	decl, err := externDecl(m)
	if err != nil {
		return "", err
	}
	// externDecl returns "export extern fun …;\n" or a variadic final — protocols
	// only carry ordinary methods, so strip the wrapper.
	line := strings.TrimPrefix(strings.TrimSpace(decl), "export extern ")
	return line, nil
}

// docComment renders doc as `///` lines, a blank doc line as a bare `///`.
// The language service reads them back as the declaration's documentation.
func docComment(doc string) string {
	doc = strings.TrimRight(doc, "\n")
	if strings.TrimSpace(doc) == "" {
		return ""
	}
	var b strings.Builder
	for line := range strings.SplitSeq(doc, "\n") {
		b.WriteString(strings.TrimRight("/// "+line, " ") + "\n")
	}
	return b.String()
}

// documentedExternDecl is externDecl behind m's doc. A variadic method has no
// typed signature to show, so its doc opens with std.BuzzSignature.
func documentedExternDecl(mod std.Module, m std.Method) (string, error) {
	decl, err := externDecl(m)
	if err != nil {
		return "", err
	}
	doc := m.Doc
	if slices.ContainsFunc(m.Args, func(a std.Arg) bool { return a.Variadic }) {
		doc = fmt.Sprintf("%s\n%s", std.BuzzSignature(mod, m), doc)
	}
	return docComment(doc) + decl, nil
}

// externDecl renders one method as `export extern fun name(params) > ret;`.
// Buzz has no variadic parameter, so a variadic method becomes an untyped `any`
// value, marked as variadic.
func externDecl(m std.Method) (string, error) {
	name := std.CamelCase(m.Name)
	if m.BuzzName != "" {
		name = m.BuzzName
	}
	for _, a := range m.Args {
		if a.Variadic {
			return fmt.Sprintf("// %s is variadic; Buzz has no variadic parameter, so it stays untyped.\nexport final %s: any = null;\n", name, name), nil
		}
	}

	params := make([]string, 0, len(m.Args))
	sig := m.Signature()
	for i, a := range m.Args {
		if sig != nil && sig.In(i+1).Kind() == reflect.Func {
			typ, err := callbackBuzzType(sig.In(i + 1))
			if err != nil {
				return "", fmt.Errorf("arg %s: %w", a.Name, err)
			}
			p := fmt.Sprintf("%s: %s", a.Name, typ)
			if a.Optional {
				// The adapter turns an absent function into a nil Go func.
				p += "? = null"
			}
			params = append(params, p)
			continue
		}
		typ, err := buzzArgType(a.Type)
		if err != nil {
			return "", fmt.Errorf("arg %s: %w", a.Name, err)
		}
		// A declared object wins over the raw tag: the shape is what the checker should
		// enforce, and {str: any} enforces nothing.
		if a.Object != "" {
			typ = a.Object
		}
		// Same rule for a closed set of strings: the enum is what the checker should
		// enforce, and `str` enforces nothing.
		if name := argumentEnum(m, i); name != "" {
			typ = name
		}
		// A byte-slice argument takes a str or a list, which Buzz cannot spell as
		// a union, so it is `any`. A byte-slice return stays [int].
		if a.Type == std.TypeByteSlice {
			typ = "any"
		}
		p := fmt.Sprintf("%s: %s%s", a.Name, typ, nullable(m, i))
		if a.Optional {
			def, derr := optionalDefault(m, i)
			if derr != nil {
				return "", fmt.Errorf("arg %s: %w", a.Name, derr)
			}
			p += " = " + def
		}
		params = append(params, p)
	}
	ret, err := buzzReturnType(m)
	if err != nil {
		return "", err
	}
	// Host errors cross the VM as a map (see ffi/convert.go), not a str,
	// so a raising method declares `!> any`.
	raises := ""
	if m.Raises {
		raises = " !> any"
	}
	return fmt.Sprintf("export extern fun %s(%s) > %s%s;\n", name, strings.Join(params, ", "), ret, raises), nil
}

// optionalRecord reports whether argument i is an optional object, not a list.
// It defaults to null, not `T{}`, which could name another module's record.
func optionalRecord(m std.Method, i int) bool {
	a := m.Args[i]
	return a.Optional && a.Object != "" && !strings.HasPrefix(a.Object, "[")
}

func nullable(m std.Method, i int) string {
	if optionalRecord(m, i) {
		return "?"
	}
	return ""
}

func optionalDefault(m std.Method, i int) (string, error) {
	if optionalRecord(m, i) {
		return "null", nil
	}
	if obj := m.Args[i].Object; obj != "" {
		return fmt.Sprintf("[<%s>]", strings.Trim(obj, "[]")), nil
	}
	return buzzDefault(m.Args[i])
}

// buzzArgType maps a parameter's TypeTag to its Buzz annotation.
func buzzArgType(t std.TypeTag) (string, error) {
	if name := t.BuzzName(); name != "" {
		return name, nil
	}
	return "", fmt.Errorf("no Buzz annotation for type tag %d", t)
}

// buzzDefault renders the default of an optional parameter: Arg.Default, not
// the type's zero. It dispatches on the declared tag, so a mismatch fails here.
func buzzDefault(a std.Arg) (string, error) {
	if a.Default == nil {
		return buzzZero(a.Type)
	}
	mismatch := func() error {
		return fmt.Errorf("default %#v (%T) does not match the declared type tag %d", a.Default, a.Default, a.Type)
	}
	switch a.Type {
	case std.TypeString:
		v, ok := a.Default.(string)
		if !ok {
			return "", mismatch()
		}
		return strconv.Quote(v), nil
	case std.TypeBool:
		v, ok := a.Default.(bool)
		if !ok {
			return "", mismatch()
		}
		return strconv.FormatBool(v), nil
	case std.TypeInt, std.TypeIndex:
		if lit, ok := intLiteral(a.Default); ok {
			return lit, nil
		}
		return "", mismatch()
	case std.TypeFloat:
		if lit, ok := floatLiteral(a.Default); ok {
			return lit, nil
		}
		return "", mismatch()
	case std.TypeAny, std.TypeAnyMap, std.TypeByteSlice, std.TypeFloatSlice, std.TypeInvalid, std.TypeStringMap, std.TypeStringMapMap, std.TypeStringSlice, std.TypeStringSliceSlice:
	}
	return "", fmt.Errorf("no Buzz literal for a default on type tag %d", a.Type)
}

func intLiteral(v any) (string, bool) {
	switch n := v.(type) {
	case int:
		return strconv.Itoa(n), true
	case int64:
		return strconv.FormatInt(n, 10), true
	}
	return "", false
}

func floatLiteral(v any) (string, bool) {
	switch n := v.(type) {
	case float64:
		return strconv.FormatFloat(n, 'f', -1, 64), true
	case int:
		return strconv.FormatFloat(float64(n), 'f', -1, 64), true
	}
	return "", false
}

// buzzZero is the default for an optional parameter that declares none.
// An unmapped tag is an error: `null` is not the zero of any other tag.
func buzzZero(t std.TypeTag) (string, error) {
	switch t {
	case std.TypeString:
		return `""`, nil
	case std.TypeInt, std.TypeIndex:
		return "0", nil
	case std.TypeFloat:
		return "0.0", nil
	case std.TypeBool:
		return "false", nil
	case std.TypeAny:
		// The one tag whose zero really is null: `any` is nullable, so `x: any = null`
		// annotates cleanly.
		return "null", nil
	case std.TypeAnyMap, std.TypeByteSlice, std.TypeFloatSlice, std.TypeInvalid, std.TypeStringMap, std.TypeStringMapMap, std.TypeStringSlice, std.TypeStringSliceSlice:
	}
	return buzzEmptyLiteral(t)
}

// buzzEmptyLiteral is a list or map zero: its annotation as an empty literal.
func buzzEmptyLiteral(t std.TypeTag) (string, error) {
	typ, err := buzzArgType(t)
	if err != nil || (typ[0] != '[' && typ[0] != '{') {
		return "", fmt.Errorf("optional arg of type tag %d has no expressible Buzz default", t)
	}
	last := len(typ) - 1
	return fmt.Sprintf("%s<%s>%s", typ[:1], typ[1:last], typ[last:]), nil
}

// buzzReturnType renders a method's Buzz return annotation.
//
// Several returns marshal to a list, so the annotation follows the wire
// shape: the element type when the returns agree, else [any].
func buzzReturnType(m std.Method) (string, error) {
	if len(m.Returns) == 0 {
		return "void", nil
	}
	if len(m.Returns) > 1 {
		first, err := buzzArgType(m.Returns[0].Type)
		if err != nil {
			return "", err
		}
		for _, r := range m.Returns[1:] {
			t, terr := buzzArgType(r.Type)
			if terr != nil {
				return "", terr
			}
			if t != first {
				return "[any]", nil
			}
		}
		return fmt.Sprintf("[%s]", first), nil
	}
	r := m.Returns[0]
	if r.Nullable {
		if r.Type != std.TypeString || r.Object != "" {
			return "", fmt.Errorf("a nullable return is a str?, not %s", r.Type.GoType())
		}
		return "str?", nil
	}
	if r.Object != "" {
		return r.Object, nil
	}
	return buzzArgType(r.Type)
}

// collectMirrors returns the mirrors a module must carry, leaf-first.
// An unresolvable name is an error: a missing mirror parses but fails the check.
func collectMirrors(mod std.Module) ([]string, error) {
	seen := map[string]bool{}
	var order []string
	var visit func(name string) error
	visit = func(name string) error {
		if name == "" || seen[name] {
			return nil
		}
		entry, ok := boundaryTypeIn(mod.Name, name)
		if !ok {
			return fmt.Errorf("object %q does not cross into Buzz: no host signature or boundaryRoots entry reaches it", name)
		}
		seen[name] = true // before descending, so a self-referential type terminates
		name, here := declaredHere(mod, entry, name, seen)
		if !here {
			return nil
		}
		for _, dep := range referencedObjects(mod.Name, entry.Type) {
			if err := visit(dep); err != nil {
				return fmt.Errorf("%s: %w", name, err)
			}
		}
		order = append(order, name) // after its dependencies: declare-before-use
		return nil
	}
	// Arguments name types as returns do: http\get's `retry: HttpRetry` needs
	// its mirror declared.
	visitMethod := func(m std.Method) error {
		for _, obj := range methodObjects(m) {
			if err := visit(obj); err != nil {
				return fmt.Errorf("%s: %w", m.Name, err)
			}
		}
		return nil
	}
	for _, m := range slices.Concat(sortedMethods(mod), mod.ObjectExterns()) {
		if err := visitMethod(m); err != nil {
			return nil, err
		}
	}
	// A namespace member references objects like a top-level method does
	// (magus\ledger.list returns JobList), so it needs the same walk.
	for _, ns := range mod.Namespaces {
		for _, m := range sortedNamespaceMethods(ns) {
			if err := visitMethod(m); err != nil {
				return nil, fmt.Errorf("namespace %s: %w", ns.Name, err)
			}
		}
		for _, name := range ns.Objects {
			if err := visit(name); err != nil {
				return nil, fmt.Errorf("namespace %s: %w", ns.Name, err)
			}
		}
	}
	for _, name := range mod.CallbackObjects {
		if err := visit(name); err != nil {
			return nil, err
		}
	}
	for _, p := range sortedProtocols(mod) {
		for _, m := range p.Methods {
			if err := visitMethod(m); err != nil {
				return nil, fmt.Errorf("protocol %s: %w", p.Name, err)
			}
		}
	}
	return order, nil
}

// methodObjects are the object names m's arguments and returns spell, list
// brackets trimmed, arguments first.
func methodObjects(m std.Method) []string {
	out := make([]string, 0, len(m.Args)+len(m.Returns))
	for _, a := range m.Args {
		out = append(out, strings.Trim(a.Object, "[]"))
	}
	for i, r := range m.Returns {
		if sig := m.Signature(); sig != nil && i < sig.NumOut() {
			if arg, ok := emit.ResultArgument(sig.Out(i)); ok {
				if arg.Kind() == reflect.Struct {
					out = append(out, buzzName(arg))
				}
				continue
			}
		}
		out = append(out, strings.Trim(r.Object, "[]"))
	}
	return out
}

// declaredHere is the name mod declares entry under, and whether this visit
// declares it. Another namespace's mirror comes from its own file.
func declaredHere(mod std.Module, entry boundaryType, name string, seen map[string]bool) (string, bool) {
	if entry.nested() && entry.Module != mod.Name {
		return "", false
	}
	own := entry.nameIn(mod.Name)
	if own != name && seen[own] {
		return "", false
	}
	seen[own] = true
	return own, true
}

// collectEnums returns the enum declarations a module's signatures and its mirrors'
// fields name, in first-use order, then the ones .buzzgen.yaml scopes to it.
func collectEnums(mod std.Module, mirrors []string) ([]boundaryEnum, error) {
	seen := map[string]bool{}
	var order []boundaryEnum
	add := func(name, where string) error {
		if name == "" || seen[name] {
			return nil
		}
		e, ok := boundaryEnumNamed(name)
		if !ok {
			return fmt.Errorf("%s: enum %q does not cross into Buzz: add its type to boundaryRoots", where, name)
		}
		seen[name] = true
		if e.nested() && e.Module != mod.Name {
			return nil
		}
		order = append(order, e)
		return nil
	}
	for _, m := range slices.Concat(sortedMethods(mod), mod.ObjectExterns()) {
		for i := range m.Args {
			if err := add(argumentEnum(m, i), m.Name); err != nil {
				return nil, err
			}
		}
		for _, r := range m.Returns {
			if err := add(r.Enum, m.Name); err != nil {
				return nil, err
			}
		}
	}
	for _, p := range sortedProtocols(mod) {
		for _, m := range p.Methods {
			for i := range m.Args {
				if err := add(argumentEnum(m, i), fmt.Sprintf("%s.%s", p.Name, m.Name)); err != nil {
					return nil, err
				}
			}
			for _, r := range m.Returns {
				if err := add(r.Enum, fmt.Sprintf("%s.%s", p.Name, m.Name)); err != nil {
					return nil, err
				}
			}
		}
	}
	for _, name := range mirrors {
		entry, _ := boundaryTypeIn(mod.Name, name)
		for _, e := range enumsUsedBy(entry.Type) {
			if err := add(e.Name, name); err != nil {
				return nil, err
			}
		}
	}
	for _, e := range boundaryEnumList() {
		if e.Module == mod.Name {
			if err := add(e.Name, mod.Name); err != nil {
				return nil, err
			}
		}
	}
	return order, nil
}

// argumentEnum also recognizes a closed string carried by the Go signature.
func argumentEnum(m std.Method, i int) string {
	if name := m.Args[i].Enum; name != "" {
		return name
	}
	if sig := m.Signature(); sig != nil && i+1 < sig.NumIn() {
		t := sig.In(i + 1)
		if t.Kind() == reflect.String && t.PkgPath() != "" {
			if enum, ok := buzzEnum(t); ok {
				return enum.Name
			}
		}
	}
	return ""
}

// buzzBuiltinTypes are the type names the Buzz type parser knows without a declaration.
var buzzBuiltinTypes = map[string]bool{
	"int": true, "double": true, "str": true, "bool": true, "null": true, "void": true,
	"any": true, "ud": true, "pat": true, "fib": true, "rg": true, "type": true,
	"fun": true, "mut": true, "obj": true,
}

var (
	buzzTypeIdent = regexp.MustCompile(`[A-Za-z_]\w*(?:\\[A-Za-z_]\w*)*`)
	// A function type's `name:` parameter label, which is not a type.
	buzzParamLabel = regexp.MustCompile(`([(,]\s*)\w+\s*:`)
)

// undeclaredTypeNames lists, sorted, every type name prog's annotations use that prog
// itself does not declare. A bundle runs alone, so another bundle's name breaks it.
func undeclaredTypeNames(prog *ast.Program) []string {
	declared := map[string]bool{}
	var imported []string
	var annots []string
	fun := func(f *ast.FunDecl) {
		annots = append(annots, f.ParamAnnots...)
		annots = append(annots, f.RetAnnot, f.YieldAnnot)
	}
	for _, stmt := range prog.Stmts {
		switch d := stmt.(type) {
		case *ast.ImportStmt:
			imported = append(imported, qualifiedName(d.Path, ""))
		case *ast.ObjectDecl:
			declared[d.Name] = true
			for _, f := range slices.Concat(d.Fields, d.StaticFields) {
				annots = append(annots, f.TypeAnnot)
			}
			for _, m := range d.Methods {
				fun(m)
			}
		case *ast.EnumDecl:
			declared[d.Name] = true
		case *ast.FunDecl:
			fun(d)
		case *ast.DeclStmt:
			annots = append(annots, d.TypeAnnot)
		}
	}
	missing := map[string]bool{}
	for _, a := range annots {
		for _, name := range buzzTypeIdent.FindAllString(buzzParamLabel.ReplaceAllString(a, "$1"), -1) {
			fromImport := slices.ContainsFunc(imported, func(ns string) bool { return strings.HasPrefix(name, ns) })
			if !buzzBuiltinTypes[name] && !declared[name] && !fromImport {
				missing[name] = true
			}
		}
	}
	return slices.Sorted(maps.Keys(missing))
}

// sortedMethods orders a module's methods by name, so reordering methods in a
// std module cannot rewrite the generated file.
func sortedMethods(mod std.Module) []std.Method {
	methods := slices.Clone(mod.Methods)
	slices.SortFunc(methods, func(a, b std.Method) int { return strings.Compare(a.Name, b.Name) })
	return methods
}

// referencedObjects lists the Buzz object names rt's fields reference.
// time.Time is excluded: it crosses as an RFC3339 str, so no "Time" mirror exists.
func referencedObjects(module string, rt reflect.Type) []string {
	var out []string
	for _, f := range emit.ObjectFields(rt) {
		t := f.Type
		for t.Kind() == reflect.Slice || t.Kind() == reflect.Array || t.Kind() == reflect.Pointer || t.Kind() == reflect.Map {
			t = t.Elem()
		}
		if t.Kind() == reflect.Struct && t != reflect.TypeFor[time.Time]() {
			out = append(out, buzzNameIn(module, t))
		}
	}
	return out
}

func runTypes(args []string) error {
	fs := flag.NewFlagSet("types", flag.ExitOnError)
	typeName := fs.String("type", "", "value type to mirror (e.g. ExecResult)")
	outPath := fs.String("out", "", "output .buzz file path")
	if err := fs.Parse(args); err != nil {
		return err
	}

	rt, ok := registry[*typeName]
	if !ok || *outPath == "" {
		return fmt.Errorf("usage: magus-utils types -type <Name> -out <path.buzz>")
	}

	out, err := renderBuzzMirror(*typeName, rt)
	if err != nil {
		return err
	}
	if err := emit.File(*outPath, out); err != nil {
		return fmt.Errorf("write %s: %w", *outPath, err)
	}
	return nil
}

// renderBuzzMirror renders rt as an `export object <name> { … }` declaration. Each exported
// field becomes a Buzz field with the mapped type and its zero-value default.
func renderBuzzMirror(name string, rt reflect.Type) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by magus-utils types. DO NOT EDIT.")
	fmt.Fprintln(&b, "//")
	// rt.Name(), not the registry key: the two differ wherever the Buzz name reads
	// better than the Go one (Projects/ProjectsOutput, HttpResponse/HTTPResponse),
	// and a header that names a type the reader cannot find defeats its purpose.
	fmt.Fprintf(&b, "// Buzz mirror of github.com/egladman/magus/types.%s, bundled into\n", rt.Name())
	fmt.Fprintln(&b, "// whichever module owns it (magus/spell, or the host module that returns it -")
	fmt.Fprintln(&b, "// see internal/spell/target.go and hosttypes.go). Edit the Go struct and rerun")
	fmt.Fprintln(&b, "// `go generate`, never this file.")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "export object %s {\n", name)
	if err := renderFields(&b, rt); err != nil {
		return nil, err
	}
	fmt.Fprintln(&b, "}")
	return b.Bytes(), nil
}

// renderFields writes one Buzz field line per exported field of rt, INLINING the
// fields of an embedded struct rather than nesting it under the embedded type's
// name.
//
// Inlining is not a style preference: encoding/json promotes an anonymous field's
// keys to the outer object, so nesting here would make the Buzz mirror and the
// JSON wire form describe the SAME Go type with two different shapes. A magusfile
// reading a value that arrived as JSON would find the fields one level shallower
// than the object it was typechecked against.
func renderFields(b *bytes.Buffer, rt reflect.Type) error {
	for i := 0; i < rt.NumField(); i++ {
		f := rt.Field(i)
		if !f.IsExported() {
			continue
		}
		// A `buzz:"-"` tag excludes the field from the Buzz object (json:"-" style),
		// keeping it Go-only without making it unexported.
		if f.Tag.Get("buzz") == "-" {
			continue
		}
		// An embedded struct with no explicit name promotes its fields. A named
		// embedded field (`buzz:"x"`) is a deliberate request to nest it, and an
		// embedded non-struct (e.g. a named string type) has nothing to promote,
		// so both fall through to the ordinary path.
		if f.Anonymous && f.Type.Kind() == reflect.Struct && f.Tag.Get("buzz") == "" {
			if err := renderFields(b, f.Type); err != nil {
				return err
			}
			continue
		}
		bt, def, err := buzzType(f.Type)
		if err != nil {
			return fmt.Errorf("field %s: %w", f.Name, err)
		}
		fmt.Fprintf(b, "    %s: %s = %s,\n", buzzFieldName(f), bt, def)
	}
	return nil
}

// buzzType maps a Go field type to its Buzz type name and zero-value default.
func buzzType(t reflect.Type) (typeName, zero string, err error) {
	// Checked ahead of the Kind switch because a Duration IS an Int64: left to the
	// integer case it would mirror as a bare `int`, handing a magusfile a
	// nanosecond count with nothing in the type or the value saying so. It crosses
	// as its own string form ("1.5s") for the same reason time.Time crosses as
	// RFC3339 - the unit travels WITH the value. A BuzzObject emitting one must call
	// d.String(), not d.Nanoseconds().
	if t == reflect.TypeOf(time.Duration(0)) {
		return "str", `""`, nil
	}
	switch t.Kind() {
	case reflect.String:
		return "str", `""`, nil
	case reflect.Bool:
		return "bool", "false", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return "int", "0", nil
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		// Buzz has no unsigned integer, so an unsigned Go field mirrors as `int`.
		// Safe for every width up to Uint32. A Uint64 above math.MaxInt64 cannot be
		// represented and would wrap; no mirrored type carries one today, and a
		// value that large is a count of something no workspace has.
		return "int", "0", nil
	case reflect.Float32, reflect.Float64:
		return "double", "0.0", nil
	case reflect.Pointer:
		// A pointer is Go's "optional", so it mirrors as the pointed-to type made
		// nullable, defaulting to null rather than to that type's zero. Mirroring it
		// as the bare type would claim a value is always present when nil is exactly
		// what the pointer exists to express.
		elem, _, eerr := buzzType(t.Elem())
		if eerr != nil {
			return "", "", eerr
		}
		return elem + "?", "null", nil
	case reflect.Array:
		// A fixed-size array carries no length information across the boundary that
		// Buzz could enforce, so it mirrors exactly as a slice does. The Go side
		// keeps the length guarantee; Buzz sees a list.
		elem, _, eerr := buzzType(t.Elem())
		if eerr != nil {
			return "", "", eerr
		}
		return "[" + elem + "]", "[]", nil
	case reflect.Slice:
		elem, _, eerr := buzzType(t.Elem())
		if eerr != nil {
			return "", "", eerr
		}
		return "[" + elem + "]", "[]", nil
	case reflect.Struct:
		// A timestamp crosses the boundary as an RFC3339 string, never as an object:
		// every BuzzObject in types/ formats it that way (and emits "" for a zero time),
		// so mirroring it as a `Time` object would describe a value Buzz never sees.
		if t == reflect.TypeOf(time.Time{}) {
			return "str", `""`, nil
		}
		// A struct field maps to the Buzz object of the same name (e.g. ExecResult),
		// which must be generated and ordered before this type in the module source.
		// Its zero value is an empty object literal.
		return t.Name(), t.Name() + "{}", nil
	case reflect.Map:
		// A map field maps to a Buzz `{key: val}` type; the zero value is the empty
		// map literal `{}`. Used by HttpResponse.headers ({str: str}).
		keyT, _, kerr := buzzType(t.Key())
		if kerr != nil {
			return "", "", fmt.Errorf("map key: %w", kerr)
		}
		valT, _, verr := buzzType(t.Elem())
		if verr != nil {
			return "", "", fmt.Errorf("map value: %w", verr)
		}
		return "{" + keyT + ": " + valT + "}", "{}", nil
	default:
		return "", "", fmt.Errorf("unsupported Go type %s", t)
	}
}

// buzzFieldName returns the Buzz field name for a Go struct field. An explicit
// `buzz:"name"` tag wins (needed for initialisms and renames — OK → ok, Path →
// projectPath); otherwise the leading capital is lowercased to match Buzz's
// camelCase convention (Mode → mode, Pattern → pattern).
//
// A name that collides with a Buzz reserved word is emitted as a FREE IDENTIFIER
// (@"type"), which is precisely what free identifiers exist for: upstream reserves
// those words in binding positions only, so `@"type": str` declares the field and
// `entry.type` still reads it back. Without this, mirroring a Go field named Type
// or Any emits source that does not parse.
func buzzFieldName(f reflect.StructField) string {
	name := f.Tag.Get("buzz")
	if name == "" {
		name = strings.ToLower(f.Name[:1]) + f.Name[1:]
	}
	if buzz.IsReservedIdent(name) {
		return `@"` + name + `"`
	}
	return name
}

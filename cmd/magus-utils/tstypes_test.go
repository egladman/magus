func TestRunTSTypes(t *testing.T) {
	t.Run("writes every -out", func(t *testing.T) {
		dir := t.TempDir()
		a, b := filepath.Join(dir, "a.ts"), filepath.Join(dir, "b.ts")
		require.NoError(t, runTSTypes([]string{"-out", a, "-out", b}))
		gotA, err := os.ReadFile(a)
		require.NoError(t, err)
		gotB, err := os.ReadFile(b)
		require.NoError(t, err)
		assert.Equal(t, string(gotA), string(gotB))
	})

	t.Run("deterministic", func(t *testing.T) {
		assertDeterministic(t, runTSTypes, func(out string) []string { return []string{"-out", out} })
	})

	t.Run("no -out", func(t *testing.T) {
		require.ErrorContains(t, runTSTypes(nil), "usage:")
	})
}

func TestRenderTSTypes(t *testing.T) {
	src, err := renderTSTypes(boundaryTypes)
	require.NoError(t, err)
	got := string(src)

	assert.Contains(t, got, "// Code generated by magus-utils tstypes. DO NOT EDIT.")
	assert.Contains(t, got, "export interface Diagnostic {\n  code: string;\n  message: string;\n  url?: string;\n  fix?: string;\n}\n")
	assert.Contains(t, got, "export class MagusError extends Error {")
	assert.Contains(t, got, "export type Result<T, E extends Error = MagusError> =")
	assert.NotContains(t, got, "why", "Diagnostic.Why is not part of the boundary shape")
}

func TestRenderTSTypesRefusesUnorderedOrUnknown(t *testing.T) {
	diag := boundaryType{Name: "Diagnostic", Type: reflect.TypeFor[types.Diagnostic](), TS: true}
	result := boundaryType{Name: "Result", Type: reflect.TypeFor[types.Result[buzzgen.T]](), TS: true}

	_, err := renderTSTypes([]boundaryType{result, diag})
	require.ErrorContains(t, err, "Diagnostic must be flagged TS and precede it")

	other := boundaryType{Name: "Box", Type: reflect.TypeFor[types.Result[buzzgen.T]](), TS: true}
	_, err = renderTSTypes([]boundaryType{diag, other})
	require.ErrorContains(t, err, "no TypeScript form for a generic other than Result")
}

// tsTypeCheck exercises the generated module the way callers will: checking error
// narrows both sides for the default error, a custom Error subclass and T = undefined,
// and a non-Error error side is refused.
const tsTypeCheck = `import { attempt, fail, fromPromise, MagusError, ok, parseJSON, type Result } from "./types";

// tsc narrows on error only once E is concrete; code generic over E checks value too.
function generic<T, E extends Error>(r: Result<T, E>): T | E | undefined {
  if (r.error) {
    return r.error satisfies E;
  }
  // @ts-expect-error value stays T | undefined while E is unresolved
  return r.value satisfies T;
}

const custom: Result<number, TypeError> = fail(new TypeError("bad"));
const fallback: Result<number> = ok(1);
const nothing: Result<undefined> = ok(undefined);
const parsed: Result<unknown, MagusError> = parseJSON("{");
const thrown: Result<number> = attempt(() => 1);
const awaited: Promise<Result<string>> = fromPromise(Promise.resolve("v"));

if (custom.error) {
  custom.error satisfies TypeError;
} else {
  custom.value satisfies number;
}
if (fallback.error) {
  fallback.error.code satisfies string;
} else {
  fallback.value satisfies number;
}
if (nothing.error) {
  nothing.error satisfies MagusError;
} else {
  nothing.value satisfies undefined;
}

// @ts-expect-error the error side must be an Error
type NotAnError = Result<number, string>;

export type { NotAnError };
export { awaited, custom, fallback, generic, nothing, parsed, thrown };
`

func TestTSTypesTypeCheck(t *testing.T) {
	console, err := filepath.Abs(filepath.Join("..", "..", "console"))
	require.NoError(t, err)
	tsc := filepath.Join(console, "node_modules", ".bin", "tsc")
	if _, err := os.Stat(tsc); err != nil {
		t.Skipf("no tsc at %s: run ./magus run install console", tsc)
	}

	dir := t.TempDir()
	src, err := renderTSTypes(boundaryTypes)
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(filepath.Join(dir, "types.ts"), src, 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "check.ts"), []byte(tsTypeCheck), 0o600))
	config := `{"compilerOptions": {"target": "ES2022", "module": "ESNext", "moduleResolution": "bundler",
  "lib": ["ES2022"], "strict": true, "noEmit": true, "skipLibCheck": true, "types": [],
  "paths": {"@connectrpc/connect": ["` + filepath.ToSlash(filepath.Join(console, "node_modules", "@connectrpc", "connect")) + `"]}},
  "files": ["types.ts", "check.ts"]}`
	require.NoError(t, os.WriteFile(filepath.Join(dir, "tsconfig.json"), []byte(config), 0o600))

	out, err := exec.CommandContext(t.Context(), tsc, "-p", dir).CombinedOutput()
	require.NoError(t, err, "tsc:\n%s", out)
}

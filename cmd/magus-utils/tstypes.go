func init() { scribes["tstypes"] = runTSTypes }

// runTSTypes writes the TypeScript form of every boundary type flagged TS to each -out.
// The console and docs bundle separately, so each gets its own copy.
func runTSTypes(args []string) error {
	fs := flag.NewFlagSet("tstypes", flag.ExitOnError)
	var outs []string
	fs.Func("out", "output .ts file path (repeatable)", func(s string) error {
		outs = append(outs, s)
		return nil
	})
	if err := fs.Parse(args); err != nil {
		return err
	}
	if len(outs) == 0 {
		return fmt.Errorf("usage: magus-utils tstypes -out <path.ts> [-out <path.ts>...]")
	}
	src, err := renderTSTypes(boundaryTypes)
	if err != nil {
		return err
	}
	for _, out := range outs {
		if err := emit.File(out, src); err != nil {
			return fmt.Errorf("write %s: %w", out, err)
		}
	}
	return nil
}

// renderTSTypes renders the TS-flagged entries in registry order. A plain struct becomes
// an interface over its JSON shape; Result becomes a union a TypeScript caller narrows
// on `error`, as Go code checks err, with a MagusError built from the Diagnostic
// interface as its default error.
func renderTSTypes(entries []boundaryType) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by magus-utils tstypes. DO NOT EDIT.")
	fmt.Fprintln(&b, "//")
	fmt.Fprintln(&b, "// TypeScript forms of the boundary types flagged TS in cmd/magus-utils/boundary_types.go.")
	fmt.Fprintln(&b, "// Edit the Go struct and run `magus run types-generate`, never this file.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, `import { Code, ConnectError } from "@connectrpc/connect";`)
	declared := map[string]bool{}
	for _, e := range entries {
		if !e.TS {
			continue
		}
		fmt.Fprintln(&b)
		if len(buzzgen.TypeParams(e.Type)) > 0 {
			if e.Name != "Result" {
				return nil, fmt.Errorf("boundary type %s: no TypeScript form for a generic other than Result", e.Name)
			}
			if !declared["Diagnostic"] {
				return nil, fmt.Errorf("boundary type Result: Diagnostic must be flagged TS and precede it")
			}
			b.WriteString(tsResult)
			declared[e.Name] = true
			continue
		}
		if err := renderTSInterface(&b, e.Name, e.Type, declared); err != nil {
			return nil, fmt.Errorf("boundary type %s: %w", e.Name, err)
		}
		declared[e.Name] = true
	}
	return b.Bytes(), nil
}

// renderTSInterface writes rt's JSON shape. A field the Buzz mirror opts out of is left
// out here too: both describe the value at the boundary, not the full Go record.
func renderTSInterface(b *bytes.Buffer, name string, rt reflect.Type, declared map[string]bool) error {
	fmt.Fprintf(b, "export interface %s {\n", name)
	for i := 0; i < rt.NumField(); i++ {
		f := rt.Field(i)
		if !f.IsExported() || f.Tag.Get("buzz") == "-" {
			continue
		}
		jsonName, opts, _ := strings.Cut(f.Tag.Get("json"), ",")
		if jsonName == "-" {
			continue
		}
		if jsonName == "" {
			jsonName = f.Name
		}
		optional := strings.Contains(opts, "omitempty") || f.Type.Kind() == reflect.Pointer
		t, err := tsType(f.Type, declared)
		if err != nil {
			return fmt.Errorf("field %s: %w", f.Name, err)
		}
		mark := ""
		if optional {
			mark = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", jsonName, mark, t)
	}
	fmt.Fprintln(b, "}")
	return nil
}

func tsType(t reflect.Type, declared map[string]bool) (string, error) {
	switch t.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Pointer:
		return tsType(t.Elem(), declared)
	case reflect.Slice, reflect.Array:
		elem, err := tsType(t.Elem(), declared)
		if err != nil {
			return "", err
		}
		return elem + "[]", nil
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("map key %s is not a string", t.Key())
		}
		val, err := tsType(t.Elem(), declared)
		if err != nil {
			return "", err
		}
		return "Record<string, " + val + ">", nil
	case reflect.Struct:
		name := buzzName(t)
		if !declared[name] {
			return "", fmt.Errorf("%s is not flagged TS ahead of its use", name)
		}
		return name, nil
	default:
		return "", fmt.Errorf("no TypeScript form for Go type %s", t)
	}
}

// tsResult is Result's TypeScript form. It is written out rather than derived: the
// union, the Error subclass and the helpers holding the only try/catch are the TS idiom,
// and none of them is a shape a Go struct carries.
const tsResult = `export class MagusError extends Error {
  readonly code: string;
  readonly url?: string;
  readonly fix?: string;

  constructor(d: Diagnostic, options?: ErrorOptions) {
    super(d.message, options);
    this.name = "MagusError";
    this.code = d.code;
    if (d.url !== undefined) this.url = d.url;
    if (d.fix !== undefined) this.fix = d.fix;
  }
}

export type Result<T, E extends Error = MagusError> =
  | { value: T; error?: undefined }
  | { value?: undefined; error: E };

export function ok<T>(value: T): Result<T, never> {
  return { value };
}

export function fail<E extends Error>(error: E): Result<never, E> {
  return { error };
}

export function attempt<T>(fn: () => T): Result<T> {
  try {
    return ok(fn());
  } catch (e) {
    return fail(toMagusError(e));
  }
}

export async function fromPromise<T>(p: Promise<T>): Promise<Result<T>> {
  try {
    return ok(await p);
  } catch (e) {
    return fail(toMagusError(e));
  }
}

export function parseJSON(text: string): Result<unknown> {
  return attempt((): unknown => JSON.parse(text));
}

function toMagusError(e: unknown): MagusError {
  if (e instanceof MagusError) return e;
  if (e instanceof ConnectError) {
    return new MagusError({ code: Code[e.code], message: e.rawMessage }, { cause: e });
  }
  const message = e instanceof Error ? e.message : String(e);
  return new MagusError({ code: "", message }, { cause: e });
}
`

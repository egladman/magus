// The inbound list names registry entries by their Buzz name, so a typo or a type
// dropped from boundaryTypes must fail here rather than at generate time in CI.
func TestInboundTypesAreRegistered(t *testing.T) {
	seen := map[string]bool{}
	for _, name := range inboundTypes {
		assert.False(t, seen[name], "%s is listed twice", name)
		seen[name] = true
		_, ok := boundaryTypeNamed(name)
		assert.True(t, ok, "inbound type %s is not in boundaryTypes", name)
	}
}

func TestRunBoundaryDecode(t *testing.T) {
	dir := t.TempDir()
	args := func(n string) []string {
		return []string{"-out", filepath.Join(dir, n+"decode.go"), "-list", filepath.Join(dir, n+"list_test.go")}
	}
	read := func(n string) (string, string) {
		require.NoError(t, runBoundaryDecode(args(n)))
		dec, err := os.ReadFile(filepath.Join(dir, n+"decode.go"))
		require.NoError(t, err)
		list, err := os.ReadFile(filepath.Join(dir, n+"list_test.go"))
		require.NoError(t, err)
		return string(dec), string(list)
	}

	dec, list := read("a")
	assert.Contains(t, dec, "Code generated by magus-utils boundarydecode. DO NOT EDIT.")
	assert.Contains(t, dec, "package decode")
	assert.Contains(t, dec, "func DecodeLanguage(v vm.Value) (spells.Language, error)")
	assert.Contains(t, dec, `return decodeLanguage(v, "language")`)
	// The key is the mirror's field name, tag renames included, never the Go name.
	assert.Contains(t, dec, `case "blockComments":`)
	assert.Contains(t, dec, `case "ignoreEscape":`)
	assert.NotContains(t, dec, "bindings/gen\"", "the decode package must stay light enough for internal/spell to import")
	assert.Contains(t, list, "package decode_test")
	assert.Contains(t, list, `{Name: "Language", Zero: spells.Language{}`)

	dec2, list2 := read("b")
	assert.Equal(t, dec, dec2, "the generated bytes must not depend on map order")
	assert.Equal(t, list, list2)

	t.Run("no -out", func(t *testing.T) {
		err := runBoundaryDecode(nil)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "usage:")
	})
}

// A struct an inbound type carries must be inbound itself, so its decoder exists and is
// round-trip tested; generating a private one silently would cover it with neither.
func TestDecodeEmitterRefusesANestedTypeThatIsNotInbound(t *testing.T) {
	lang, ok := boundaryTypeNamed("Language")
	require.True(t, ok)
	e := newDecodeEmitter([]boundaryType{lang})
	err := e.emitStruct(lang)
	require.Error(t, err)
	assert.Contains(t, err.Error(), "add CommentSyntax to inboundTypes")
}

// Every spell contract type must already generate, so a later unit marking one inbound
// changes the list and nothing else. Tool reaches enums, maps of structs, optional
// pointers and Command with its charms.
func TestDecodeEmitterGeneratesTheContractTypes(t *testing.T) {
	for _, root := range []reflect.Type{
		reflect.TypeFor[spells.Tool](), reflect.TypeFor[spells.Sandbox](), reflect.TypeFor[spells.Manifest](),
		reflect.TypeFor[spells.SymbolIndexer](), reflect.TypeFor[spells.Service](), reflect.TypeFor[types.Path](),
	} {
		closure := boundaryClosure(t, root)
		e := newDecodeEmitter(closure)
		for _, entry := range closure {
			require.NoError(t, e.emitStruct(entry), "%s", entry.Name)
		}
		src, err := e.file()
		require.NoError(t, err, "%s", root)
		assert.Contains(t, string(src), "func Decode"+root.Name()+"(")
	}
}

// boundaryClosure lists the registry entries reachable from root's fields, root last.
func boundaryClosure(t *testing.T, root reflect.Type) []boundaryType {
	t.Helper()
	var out []boundaryType
	seen := map[reflect.Type]bool{}
	var visit func(reflect.Type)
	visit = func(rt reflect.Type) {
		switch rt.Kind() {
		case reflect.Pointer, reflect.Slice, reflect.Map:
			visit(rt.Elem())
			return
		case reflect.Struct:
			if rt == reflect.TypeFor[time.Time]() {
				return
			}
		default:
			return
		}
		if seen[rt] {
			return
		}
		seen[rt] = true
		for _, f := range boundaryFields(rt) {
			visit(f.Type)
		}
		entry, ok := boundaryTypeNamed(buzzName(rt))
		require.True(t, ok, "%s is not registered", rt)
		out = append(out, entry)
	}
	visit(root)
	return out
}

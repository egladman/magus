package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"
)

type generator struct {
	types   map[string]ast.Expr
	names   map[string]string
	written map[string]bool
	out     bytes.Buffer
}

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: jobschema JOB_DIR APIVERSION_DIR")
	}
	job := os.Args[1]
	g := generator{types: make(map[string]ast.Expr), names: make(map[string]string), written: make(map[string]bool)}
	g.load(job, "")
	g.load(os.Args[2], "apiversion.")
	roots := []string{"jobRecord", "attemptRecord", "grantRecord", "checkRunRecord", "gradeRecord"}
	for _, r := range roots {
		n := strings.TrimSuffix(r, "Record")
		g.names[r] = strings.ToUpper(n[:1]) + n[1:]
	}
	g.out.WriteString("// Code generated by jobschema. DO NOT EDIT.\n\npackage gen\n\nimport \"github.com/egladman/magus/libs/codec\"\n")
	for _, r := range roots {
		g.object(r)
	}
	code, err := format.Source(g.out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	dest := filepath.Join(job, "internal", "gen")
	if err := os.MkdirAll(dest, 0755); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dest, "schema.go"), code, 0644); err != nil {
		log.Fatal(err)
	}
}

func (g *generator) load(dir, prefix string) {
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		log.Fatal(err)
	}
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.SkipObjectResolution)
		if err != nil {
			log.Fatal(err)
		}
		for _, decl := range f.Decls {
			d, ok := decl.(*ast.GenDecl)
			if !ok || d.Tok != token.TYPE {
				continue
			}
			for _, spec := range d.Specs {
				t := spec.(*ast.TypeSpec)
				g.types[prefix+t.Name.Name] = t.Type
			}
		}
	}
}

func (g *generator) child(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.StarExpr:
		return g.child(t.X)
	case *ast.ArrayType:
		if elem := g.child(t.Elt); elem != "nil" {
			return "&codec.ObjectSchema{Element:" + elem + "}"
		}
	case *ast.Ident:
		if !t.IsExported() && g.types[t.Name] != nil {
			return g.object(t.Name)
		}
	case *ast.MapType:
		if g.child(t.Value) != "nil" {
			log.Fatal("job schema: map of store-owned objects needs a key policy")
		}
	case *ast.SelectorExpr: // Imported types own their encoding.
	default:
		log.Fatalf("job schema: unsupported field type %T", expr)
	}
	return "nil"
}

func (g *generator) object(name string) string {
	id := g.names[name]
	if id == "" {
		id = name
	}
	if g.written[name] {
		return "&" + id
	}
	g.written[name] = true
	var fields strings.Builder
	closed := true
	g.fields(name, &fields, &closed, map[string]bool{})
	fmt.Fprintf(&g.out, "\nvar %s = codec.ObjectSchema{Name:%q, Closed:%t, Fields:map[string]*codec.ObjectSchema{\n%s}}\n", id, name, closed, fields.String())
	return "&" + id
}

func (g *generator) fields(name string, out *strings.Builder, closed *bool, seen map[string]bool) {
	obj, ok := g.types[name].(*ast.StructType)
	if !ok {
		log.Fatalf("job schema: expected struct %s", name)
	}
	for _, f := range obj.Fields.List {
		var tag reflect.StructTag
		if f.Tag != nil {
			raw, err := strconv.Unquote(f.Tag.Value)
			if err != nil {
				log.Fatal(err)
			}
			tag = reflect.StructTag(raw)
		}
		key, options, _ := strings.Cut(tag.Get("json"), ",")
		if tag.Get("codec") == "unknown" {
			*closed = false
		}
		if key == "-" {
			continue
		}
		for opt := range strings.SplitSeq(options, ",") {
			if opt != "" && opt != "omitzero" && opt != "omitempty" {
				log.Fatalf("job schema: unsupported JSON option %q in %s", opt, name)
			}
		}
		if len(f.Names) == 0 {
			sel, ok := f.Type.(*ast.SelectorExpr)
			if !ok || key != "" || sel.Sel.Name != "TypeMeta" || !isIdent(sel.X, "apiversion") {
				log.Fatalf("job schema: unsupported embedding in %s", name)
			}
			g.fields("apiversion.TypeMeta", out, closed, seen)
			continue
		}
		for _, field := range f.Names {
			if !field.IsExported() {
				continue
			}
			k := key
			if k == "" {
				k = field.Name
			}
			if seen[k] {
				log.Fatalf("job schema: ambiguous JSON member %s.%s", name, k)
			}
			seen[k] = true
			fmt.Fprintf(out, "%q:%s,\n", k, g.child(f.Type))
		}
	}
}

func isIdent(x ast.Expr, name string) bool { id, ok := x.(*ast.Ident); return ok && id.Name == name }

package job

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"reflect"
	"strconv"
	"strings"
	"testing"
)

var updateSchema = flag.Bool("update-job-schema", false, "regenerate the stored job field tables")

// Only the generator inspects Go types. The reader follows the generated table.
func TestStoredSchemas(t *testing.T) {
	roots := []struct {
		name  string
		value any
	}{
		{"Job", jobRecord{}}, {"Attempt", attemptRecord{}}, {"Grant", grantRecord{}},
		{"CheckRun", checkRunRecord{}}, {"Grade", gradeRecord{}},
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by TestStoredSchemas. DO NOT EDIT.\n\npackage gen\n\nimport \"github.com/egladman/magus/libs/codec\"\n")
	names := map[reflect.Type]string{}
	for _, r := range roots {
		names[reflect.TypeOf(r.value)] = r.name
	}
	written := map[reflect.Type]bool{}
	var schema func(reflect.Type) string
	schema = func(typ reflect.Type) string {
		switch typ.Kind() {
		case reflect.Pointer:
			return schema(typ.Elem())
		case reflect.Array, reflect.Slice:
			if elem := schema(typ.Elem()); elem != "nil" {
				return "&codec.ObjectSchema{Element:" + elem + "}"
			}
			return "nil"
		case reflect.Struct:
		default:
			return "nil"
		}
		// Exported domain values own their encoding. Private wire structs belong to this store.
		if typ.PkgPath() != reflect.TypeFor[jobRecord]().PkgPath() || typ.Name() == "" || token.IsExported(typ.Name()) {
			return "nil"
		}
		id := names[typ]
		if id == "" {
			id = typ.Name()
		}
		if written[typ] {
			return "&" + id
		}
		written[typ] = true
		closed := true
		var fields strings.Builder
		for _, f := range reflect.VisibleFields(typ) {
			if f.Anonymous || !f.IsExported() {
				continue
			}
			if f.Tag.Get("codec") == "unknown" {
				closed = false
			}
			key, _, _ := strings.Cut(f.Tag.Get("json"), ",")
			if key == "-" {
				continue
			}
			if key == "" {
				key = f.Name
			}
			fmt.Fprintf(&fields, "%s:%s,\n", strconv.Quote(key), schema(f.Type))
		}
		fmt.Fprintf(&out, "\nvar %s = codec.ObjectSchema{Name:%q, Closed:%t, Fields:map[string]*codec.ObjectSchema{\n%s}}\n", id, typ.Name(), closed, fields.String())
		return "&" + id
	}
	for _, r := range roots {
		schema(reflect.TypeOf(r.value))
	}
	want, err := format.Source(out.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	const path = "internal/gen/schema.go"
	if *updateSchema {
		if err := os.WriteFile(path, want, 0644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(want, got) {
		t.Fatal("stored field tables are stale; regenerate with TestStoredSchemas -update-job-schema")
	}
}

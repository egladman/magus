package proofread

import (
	"slices"
	"strconv"
	"testing"
)

// placesOf returns each block's start line and place, in file order.
func placesOf(t *testing.T, src string, lang SourceLanguage) []string {
	t.Helper()

	var out []string

	for _, c := range readCode(src, lang).comments {
		out = append(out, string(c.place)+":"+strconv.Itoa(c.start))
	}

	return out
}

func assertPlaces(t *testing.T, got []string, want ...string) {
	t.Helper()

	if !slices.Equal(got, want) {
		t.Errorf("places = %v, want %v", got, want)
	}
}

func TestReadCodePlacesGoComments(t *testing.T) {
	src := "// Package p is small.\npackage p\n\n" +
		"// Exported is part of the API.\nfunc Exported() {\n\t// inside a body\n\tx()\n\ty() // after code\n}\n\n" +
		"// helper is not.\nfunc helper() {}\n\n" +
		"type T struct {\n\t// Name is a field doc.\n\tName string\n\t// age is unexported.\n\tage int\n}\n"

	assertPlaces(t, placesOf(t, src, LanguageGo),
		"header:1", "exported-doc:4", "inline:6", "trailing:8", "doc:11", "exported-doc:15", "doc:17")
}

func TestReadCodeKeepsGoDirectivesAndGeneratedFilesOut(t *testing.T) {
	src := "//go:build linux\n\npackage p\n\n//nolint:errcheck\nfunc f() {}\n"
	if got := placesOf(t, src, LanguageGo); len(got) != 0 {
		t.Errorf("directives are no comments, got %v", got)
	}

	gen := "// Code generated by tool. DO NOT EDIT.\n\npackage p\n\n// f is long enough to judge.\nfunc f() {}\n"
	if got := placesOf(t, gen, LanguageGo); len(got) != 0 {
		t.Errorf("a generated file holds no comments, got %v", got)
	}
}

func TestReadCodeIgnoresSlashesInStrings(t *testing.T) {
	src := "package p\n\nvar u = \"https://example.com\"\nvar r = `// not a comment`\n"
	if got := placesOf(t, src, LanguageGo); len(got) != 0 {
		t.Errorf("a URL or raw string is code, got %v", got)
	}
}

func TestReadCodePlacesTypeScriptComments(t *testing.T) {
	src := "// The module header.\n\nimport { x } from \"y\";\n\n" +
		"/** Shown is exported. */\nexport function shown() {\n  // inside\n  return x;\n}\n\n" +
		"// hidden is module-private.\nfunction hidden() {}\n\n" +
		"export class C {\n  // field is part of C.\n  field = 1;\n  // secret is private.\n  private secret = 2;\n}\n"

	assertPlaces(t, placesOf(t, src, LanguageTypeScript),
		"header:1", "exported-doc:5", "inline:7", "doc:11", "exported-doc:15", "doc:17")
}

func TestReadCodePlacesBuzzComments(t *testing.T) {
	src := "// The module header.\nnamespace m;\n\n" +
		"// shown is exported.\nexport fun shown() > void {\n    // inside\n    x();\n}\n\n" +
		"// Hidden is the module's own.\nobject Hidden {\n    // n counts.\n    n: int,\n}\n"

	assertPlaces(t, placesOf(t, src, LanguageBuzz),
		"header:1", "exported-doc:4", "inline:6", "doc:10", "doc:12")
}

func TestReadCodeBlanksAMarkedParagraphOnly(t *testing.T) {
	src := "package p\n\n// f does a thing.\n//\n// TODO: make it do two\n// things at once.\nfunc f() {}\n"

	c := readCode(src, LanguageGo).comments
	if len(c) != 1 || c[0].text != "f does a thing.\n\n\n" {
		t.Errorf("comments = %#v, want the TODO paragraph blanked and the first kept", c)
	}
}

func TestReadCodeRecordsBanners(t *testing.T) {
	src := "package p\n\nfunc f() {\n\t// ---- setup ----\n\tx()\n}\n"

	c := readCode(src, LanguageGo).comments
	if len(c) != 1 || !slices.Equal(c[0].banners, []int{0}) {
		t.Errorf("comments = %#v, want one block with its banner on line 0", c)
	}
}

func TestLanguageOfReadsTheExtension(t *testing.T) {
	if got, _ := LanguageOf("a.go"); got != LanguageGo {
		t.Errorf("LanguageOf(a.go) = %q", got)
	}

	if got, _ := LanguageOf("b.tsx"); got != LanguageTypeScript {
		t.Errorf("LanguageOf(b.tsx) = %q", got)
	}

	if got, _ := LanguageOf("c.buzz"); got != LanguageBuzz {
		t.Errorf("LanguageOf(c.buzz) = %q", got)
	}

	if _, ok := LanguageOf("d.css"); ok {
		t.Error("LanguageOf(d.css) is a language")
	}
}

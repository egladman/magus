package namewords

import (
	"slices"
	"testing"

	"github.com/stretchr/testify/suite"
	"golang.org/x/tools/go/analysis/analysistest"
)

func options() Options {
	return Options{
		Suffixes: []string{"To", "For", "Of", "From"},
		ShortForms: []string{
			"Src", "Dst", "Cfg", "Msg", "Idx", "Tmp", "Ptr",
			"Ctx", "Req", "Resp", "Rsp", "Buf", "Fn", "Opts", "Str", "Strs", "Err", "Cmd", "Cwd", "Prev", "Impl", "Repo",
		},
	}
}

// TestAnalyzer covers each word list, both name spellings, a method, and each
// exemption: entry points, a method satisfying a standard library interface,
// and a generated file.
func TestAnalyzer(t *testing.T) {
	analyzer, err := New(options())
	if err != nil {
		t.Fatal(err)
	}
	analysistest.Run(t, analysistest.TestData(), analyzer, "names", "generated")
}

func TestNewRequiresAWordList(t *testing.T) {
	if _, err := New(Options{}); err == nil {
		t.Fatal("expected empty word lists to fail at construction")
	}
}

func TestSplitWords(t *testing.T) {
	for name, want := range map[string][]string{
		"graphOf":       {"graph", "Of"},
		"URLFor":        {"URL", "For"},
		"value_of":      {"value", "of"},
		"parseHTTPSrc":  {"parse", "HTTP", "Src"},
		"base64Decode":  {"base", "64", "Decode"},
		"Of":            {"Of"},
		"ensureDstSafe": {"ensure", "Dst", "Safe"},
	} {
		if got := splitWords(name); !slices.Equal(got, want) {
			t.Errorf("splitWords(%q) = %q, want %q", name, got, want)
		}
	}
}

type bannedSuite struct {
	suite.Suite
}

func TestBannedSuite(t *testing.T) { suite.Run(t, new(bannedSuite)) }

func rowRule() Banned {
	return Banned{Packages: []string{"dom/..."}, Words: []string{"Row", "Rows"}, Why: "say job or record"}
}

func (s *bannedSuite) run(rule Banned, files map[string]string, pkgs ...string) {
	analyzer, err := New(Options{Banned: []Banned{rule}})
	s.Require().NoError(err)
	dir, cleanup, err := analysistest.WriteFiles(files)
	s.Require().NoError(err)
	s.T().Cleanup(cleanup)
	analysistest.Run(s.T(), dir, analyzer, pkgs...)
}

func (s *bannedSuite) TestATypeNamedWithTheWordIsReported() {
	s.run(rowRule(), map[string]string{"dom/a/a.go": "package a\n\ntype StepRow struct{} // want `StepRow carries the word \"Row\": say job or record`\n"}, "dom/a")
}

func (s *bannedSuite) TestAFieldNamedWithTheWordIsReported() {
	s.run(rowRule(), map[string]string{"dom/a/a.go": `package a

type Report struct {
	Rows []string // want ` + "`Rows carries`" + `
	Jobs []string
}
`}, "dom/a")
}

func (s *bannedSuite) TestAFunctionAndAMethodAreReported() {
	s.run(rowRule(), map[string]string{"dom/a/a.go": `package a

type Store struct{}

func jobRows() {} // want ` + "`jobRows carries`" + `

func (Store) ModelRows() {} // want ` + "`ModelRows carries`" + `
`}, "dom/a")
}

func (s *bannedSuite) TestAConstantAndAVariableAreReported() {
	s.run(rowRule(), map[string]string{"dom/a/a.go": `package a

const ToolRowsFile = "models" // want ` + "`ToolRowsFile carries`" + `

var currentRow int // want ` + "`currentRow carries`" + `
`}, "dom/a")
}

func (s *bannedSuite) TestAnInterfaceMethodIsReported() {
	s.run(rowRule(), map[string]string{"dom/a/a.go": `package a

type Reader interface {
	ListRows() []string // want ` + "`ListRows carries`" + `
}
`}, "dom/a")
}

func (s *bannedSuite) TestAnUnexportedNameIsReported() {
	s.run(rowRule(), map[string]string{"dom/a/a.go": "package a\n\ntype stepRow struct{} // want `stepRow carries`\n"}, "dom/a")
}

func (s *bannedSuite) TestAPackageBelowTheDotsPatternIsJudged() {
	s.run(rowRule(), map[string]string{"dom/a/b/b.go": "package b\n\nfunc SpecRow() {} // want `SpecRow carries`\n"}, "dom/a/b")
}

func (s *bannedSuite) TestAPackageOutsideTheRuleIsNotJudged() {
	s.run(rowRule(), map[string]string{"store/s.go": "package store\n\ntype jobRow struct{ Rows int }\n\nfunc decodeRows() {}\n"}, "store")
}

func (s *bannedSuite) TestAnExactPathDoesNotCoverThePackagesBelowIt() {
	rule := rowRule()
	rule.Packages = []string{"dom/a"}
	s.run(rule, map[string]string{
		"dom/a/a.go":   "package a\n\nfunc OneRow() {} // want `OneRow carries`\n",
		"dom/a/b/b.go": "package b\n\nfunc TwoRow() {}\n",
	}, "dom/a", "dom/a/b")
}

func (s *bannedSuite) TestAWordInsideAnotherWordPasses() {
	s.run(rowRule(), map[string]string{"dom/a/a.go": "package a\n\nfunc Borrow() {}\n\ntype Arrow struct{ Crows int }\n"}, "dom/a")
}

func (s *bannedSuite) TestAParameterAndALocalPass() {
	s.run(rowRule(), map[string]string{"dom/a/a.go": `package a

func Keep(rows []string) (row string) {
	for _, row := range rows {
		return row
	}
	return ""
}
`}, "dom/a")
}

func (s *bannedSuite) TestAnEmbeddedFieldIsNotJudgedApartFromItsType() {
	s.run(rowRule(), map[string]string{"dom/a/a.go": "package a\n\ntype stepRow struct{} // want `stepRow carries`\n\ntype Wrap struct{ stepRow }\n"}, "dom/a")
}

func (s *bannedSuite) TestAGeneratedFilePasses() {
	s.run(rowRule(), map[string]string{"dom/a/a.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage a\n\ntype ModelRow struct{}\n"}, "dom/a")
}

func (s *bannedSuite) TestATestEntryPointPassesAndAHelperDoesNot() {
	s.run(rowRule(), map[string]string{
		"dom/a/a.go":      "package a\n",
		"dom/a/a_test.go": "package a\n\nimport \"testing\"\n\nfunc TestRows(t *testing.T) {}\n\nfunc helperRows() {} // want `helperRows carries`\n",
	}, "dom/a")
}

func (s *bannedSuite) TestTheFirstRuleThatMatchesNamesTheReport() {
	other := Banned{Packages: []string{"dom/..."}, Words: []string{"Tuple"}, Why: "say pair"}
	analyzer, err := New(Options{Banned: []Banned{rowRule(), other}})
	s.Require().NoError(err)
	dir, cleanup, err := analysistest.WriteFiles(map[string]string{"dom/a/a.go": "package a\n\nfunc RowTuple() {} // want `RowTuple carries the word \"Row\": say job`\n"})
	s.Require().NoError(err)
	s.T().Cleanup(cleanup)
	analysistest.Run(s.T(), dir, analyzer, "dom/a")
}

func (s *bannedSuite) TestARuleNamingNoPackageFailsAtConstruction() {
	_, err := New(Options{Banned: []Banned{{Words: []string{"Row"}, Why: "x"}}})
	s.ErrorContains(err, "banned[0]: packages is empty")
}


package langservice

import (
	"slices"
	"sync"
	"testing"

	"github.com/stretchr/testify/require"
	"github.com/stretchr/testify/suite"
)

// fixtureTable is a ModuleTable over an in-memory map.
type fixtureTable map[string]ModuleSource

func (t fixtureTable) Names() []string {
	names := make([]string, 0, len(t))
	for name := range t {
		names = append(names, name)
	}
	slices.Sort(names)
	return names
}

func (t fixtureTable) Module(name string) (ModuleSource, bool) {
	m, ok := t[name]
	return m, ok
}

const fsSource = `// Code generated by a fixture. DO NOT EDIT.

export object FileInfo {
    size: int = 0,
}

/// Glob returns the paths matching pattern.
///
/// Order is lexical.
export extern fun glob(pattern: str) > [str] !> any;
// Write content to path.
export extern fun writeFile(path: str, content: str) > void !> any;
export extern fun stat(
    path: str,
) > FileInfo !> any;
export extern fun join(parts: [str], sep: str = ";") > str;
/// The path separator.
export final sep: str = "/";
`

const libSource = `/// Twice doubles n.
export fun twice(n: int) > int {
    return n * 2;
}

fun hidden() > void {}
`

const vcsSource = `namespace magus\vcs;

/// Commit records the staged changes.
export extern fun commit(message: str) > str !> any;
`

func fixture() fixtureTable {
	return fixtureTable{
		"fs":        {Doc: "Filesystem access.", Source: fsSource},
		"fmt":       {Doc: "Formatting.", Source: "/// fmt\\sprintf(format, args...) -> string\n/// Format args.\nexport extern fun sprintf(format: str, args: [any]) > str;\n"},
		"lib":       {Doc: "A Buzz library.", Source: libSource},
		"magus/vcs": {Doc: "Version control.", Source: vcsSource},
		"broken":    {Doc: "Does not parse.", Source: "export fun (\n"},
	}
}

type serviceSuite struct {
	suite.Suite
	svc *Service
}

func TestServiceSuite(t *testing.T) { suite.Run(t, new(serviceSuite)) }

func (s *serviceSuite) SetupTest() { s.svc = New(fixture()) }

func (s *serviceSuite) TestMembersParsesOnFirstCall() {
	s.Empty(s.svc.parsed)
	members, err := s.svc.Members("fs")
	s.Require().NoError(err)
	s.NotEmpty(members)
	s.Len(s.svc.parsed, 1)
	s.Contains(s.svc.parsed, "fs")
}

func (s *serviceSuite) TestNamesAndDocsNeedNoParse() {
	h, ok := s.svc.Hover("broken", 2)
	s.Require().True(ok)
	s.Equal(Hover{Title: "module broken", Doc: "Does not parse."}, h)
	got := s.svc.Complete(`import "b`, len(`import "b`))
	s.Equal([]Completion{{Label: "broken", Kind: KindModule, Doc: "Does not parse.", Replace: 1}}, got)
	s.Empty(s.svc.parsed)
}

func (s *serviceSuite) TestUnparsableModuleReportsEveryCall() {
	members, err := s.svc.Members("broken")
	s.Require().Error(err)
	s.Contains(err.Error(), "module broken")
	s.Empty(members)
	_, again := s.svc.Members("broken")
	s.Equal(err, again)
	s.Empty(s.svc.Complete(`broken\`, len(`broken\`)))
}

func (s *serviceSuite) TestUnknownModuleIsAnError() {
	_, err := s.svc.Members("nope")
	s.Require().Error(err)
	s.Contains(err.Error(), `"nope"`)
}

func (s *serviceSuite) TestLoadJoinsEveryParseError() {
	err := s.svc.Load()
	s.Require().Error(err)
	s.Contains(err.Error(), "module broken")
	s.Len(s.svc.parsed, len(fixture()))

	table := fixture()
	delete(table, "broken")
	s.NoError(New(table).Load())
}

func (s *serviceSuite) TestNilTableAnswersNothing() {
	svc := New(nil)
	_, err := svc.Members("fs")
	s.Require().ErrorIs(err, errNoTable)
	s.Require().ErrorIs(svc.Load(), errNoTable)
	s.Empty(svc.Complete(`fs\`, 3))
	s.Empty(svc.Complete(`import "`, 8))
	_, ok := svc.Hover(`fs\glob`, 5)
	s.False(ok)
}

func (s *serviceSuite) TestMembersReturnsACopy() {
	members, err := s.svc.Members("fs")
	s.Require().NoError(err)
	members[0].Name = "changed"
	again, err := s.svc.Members("fs")
	s.Require().NoError(err)
	s.Equal("glob", again[0].Name)
}

func (s *serviceSuite) TestConcurrentQueries() {
	var wg sync.WaitGroup
	for range 8 {
		wg.Add(2)
		go func() {
			defer wg.Done()
			s.svc.Complete(`fs\g`, 4)
		}()
		go func() {
			defer wg.Done()
			s.Error(s.svc.Load())
		}()
	}
	wg.Wait()
	m, ok := s.svc.member("fs", "glob")
	s.True(ok)
	s.Equal("glob", m.Name)
}

func (s *serviceSuite) TestNamespacedModuleResolvesThroughItsImport() {
	src := "import \"magus/vcs\";\nvcs\\"
	got := s.svc.Complete(src, len(src))
	require.Len(s.T(), got, 1)
	s.Equal(`vcs\commit(message: str) > str !> any`, got[0].Detail)
}

func BenchmarkLoad(b *testing.B) {
	table := fixture()
	delete(table, "broken")
	for b.Loop() {
		if err := New(table).Load(); err != nil {
			b.Fatal(err)
		}
	}
}

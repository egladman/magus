package stdgen

import (
	"fmt"
	"strings"

	"github.com/egladman/magus/libs/gopherbuzz/buzzgen"
)

const scalarPackage = "github.com/egladman/magus/libs/gopherbuzz/std/internal/boxed"

// SerializeCore describes the primitives supplied by the Go codec and VM.
func SerializeCore() []byte {
	var source strings.Builder
	fmt.Fprintln(&source, "// Code generated by stdgen. DO NOT EDIT.")
	fmt.Fprintln(&source, "namespace serializecore;")
	fmt.Fprintln(&source, "export object Decoded { value: any, error: str?, }")
	for _, fn := range []struct{ name, params, result string }{
		{"wrap", "definition: any, data: any", "any"},
		{"raw", "box: any", "any"},
		{"map", "definition: any, box: any", "any"},
		{"list", "definition: any, box: any", "any"},
		{"serialize", "value: any", "any"},
		{"jsonEncode", "data: any", "str"},
		{"decode", "json: str", "Decoded"},
	} {
		fmt.Fprintf(&source, "export extern fun %s(%s) > %s;\n", fn.name, fn.params, fn.result)
	}
	return []byte(source.String())
}

// Serialize renders the public serialize module. Its scalar functions come from
// the Go package that implements the same operations on native VM values.
func Serialize(moduleRoot string) ([]byte, error) {
	program, err := buzzgen.Load(moduleRoot, buzzgen.Config{}, scalarPackage)
	if err != nil {
		return nil, err
	}
	var source, scalars strings.Builder
	fmt.Fprintln(&source, "// Code generated from gopherbuzz/std by stdgen. DO NOT EDIT.")
	fmt.Fprintln(&source, "namespace serialize;")
	fmt.Fprintln(&source, `import "serializecore";`)
	fmt.Fprintln(&source, "export object JsonParseError { message: str?, }")
	fmt.Fprintln(&source, "export object Boxed {")
	// Buzz has no variadic method declaration. The callable field accepts both
	// a list path and individual path segments, as the native API does.
	fmt.Fprintln(&source, "    q: any = null,")
	fmt.Fprintln(&source, `    static fun init(data: any) > Boxed { return serializecore\wrap(Boxed, data); }`)
	for _, scalar := range []struct{ goName, name, result string }{
		{"String", "string", "str"},
		{"Boolean", "boolean", "bool"},
		{"Integer", "integer", "int"},
		{"Floating", "floating", "double"},
	} {
		for _, suffix := range []string{"", "Value"} {
			name := scalar.name + suffix
			result := scalar.result
			if suffix == "" {
				result += "?"
			}
			function := "boxed" + scalar.goName + suffix
			body, err := program.ScalarFunction(scalarPackage, function, function, result)
			if err != nil {
				return nil, err
			}
			scalars.WriteString(body)
			fmt.Fprintf(&source, "    fun %s() > %s { return %s(serializecore\\raw(this)); }\n", name, result, function)
			if scalar.name == "floating" {
				fmt.Fprintf(&source, "    fun float%s() > %s { return this.%s(); }\n", suffix, result, name)
			}
		}
	}
	for _, collection := range []struct{ name, result, empty string }{
		{"map", "{str: Boxed}", "{}"},
		{"list", "[Boxed]", "[]"},
	} {
		fmt.Fprintf(&source, "    fun %s() > %s? { return serializecore\\%s(Boxed, this); }\n", collection.name, collection.result, collection.name)
		fmt.Fprintf(&source, "    fun %sValue() > %s { return this.%s() ?? %s; }\n", collection.name, collection.result, collection.name, collection.empty)
	}
	fmt.Fprintln(&source, "}")
	source.WriteString(scalars.String())
	fmt.Fprintln(&source, `export fun serialize(value: any) > any { return serializecore\serialize(value); }`)
	fmt.Fprintln(&source, `export fun jsonEncode(data: any) > str { return serializecore\jsonEncode(data); }`)
	fmt.Fprintln(&source, "export fun jsonDecode(json: str) > Boxed !> JsonParseError {")
	fmt.Fprintln(&source, `    final decoded = serializecore\decode(json);`)
	fmt.Fprintln(&source, "    if (decoded.error -> message) { throw JsonParseError{message = message}; }")
	fmt.Fprintln(&source, "    return Boxed.init(decoded.value);")
	fmt.Fprintln(&source, "}")
	return []byte(source.String()), nil
}

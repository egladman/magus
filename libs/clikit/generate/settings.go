// generatedHeader opens every file this package renders as Go source.
const generatedHeader = "// Code generated by github.com/egladman/magus/libs/clikit/generate; DO NOT EDIT.\n"

// Target is the configuration struct generated code reads and writes.
type Target struct {
	Import string // its package path
	Type   string // its name qualified by its package, as "config.Config"

	// EnvCheck names a func(getenv func(string) string) error that ApplyEnv
	// calls first, joining what it returns; empty calls none.
	EnvCheck string
}

func (t Target) check() error {
	if t.Import == "" || t.Type == "" {
		return fmt.Errorf("target %+v names no struct: set Import and Type", t)
	}
	return nil
}

// SettingsTable renders gofmt'd Go source for package pkg declaring
// Settings, a configuration.Setting literal per entry of settings.
func SettingsTable(settings []configuration.Setting, pkg string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(generatedHeader)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import (\n\t\"github.com/egladman/magus/libs/clikit/command\"\n\t\"github.com/egladman/magus/libs/clikit/configuration\"\n)\n\n")
	b.WriteString("// Settings is every setting the configuration struct declares.\n")
	b.WriteString("var Settings = []configuration.Setting{\n")
	for _, s := range settings {
		kind, err := kindConst(s.Kind)
		if err != nil {
			return nil, fmt.Errorf("settings table: %s: %w", s.YamlPath, err)
		}
		b.WriteString("\t{\n")
		field(&b, "GoPath", s.GoPath)
		field(&b, "YamlPath", s.YamlPath)
		field(&b, "EnvVar", s.EnvVar)
		if s.Flag != (configuration.FlagNames{}) {
			fmt.Fprintf(&b, "\t\tFlag: configuration.FlagNames{Long: %q", s.Flag.Long)
			if s.Flag.Short != "" {
				fmt.Fprintf(&b, ", Short: %q", s.Flag.Short)
			}
			b.WriteString("},\n")
		}
		fmt.Fprintf(&b, "\t\tKind: command.%s,\n", kind)
		field(&b, "Usage", s.Usage)
		field(&b, "Doc", s.Doc)
		field(&b, "Default", s.Default)
		if s.Floor {
			b.WriteString("\t\tFloor: true,\n")
		}
		if s.Internal {
			b.WriteString("\t\tInternal: true,\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return gofmt("settings table", b.Bytes())
}

func field(b *bytes.Buffer, name, value string) {
	if value != "" {
		fmt.Fprintf(b, "\t\t%s: %s,\n", name, strconv.Quote(value))
	}
}

var kindConsts = map[command.Kind]string{
	command.String: "String", command.Int: "Int", command.Bool: "Bool",
	command.Float: "Float", command.Duration: "Duration", command.Text: "Text",
	command.OptionalBool: "OptionalBool", command.StringList: "StringList",
	command.StringMap: "StringMap",
}

func kindConst(k command.Kind) (string, error) {
	if c, ok := kindConsts[k]; ok {
		return c, nil
	}
	return "", fmt.Errorf("kind %q is no setting kind", k)
}

// ApplyEnv renders gofmt'd Go source for package pkg declaring ApplyEnv,
// which overlays each setting's variable on a *target.Type. The function
// returns every value it refused, joined; a refused variable leaves its
// field as it was, and an empty one counts as unset.
func ApplyEnv(settings []configuration.Setting, pkg string, target Target) ([]byte, error) {
	if err := target.check(); err != nil {
		return nil, fmt.Errorf("apply env: %w", err)
	}
	var body bytes.Buffer
	imports := map[string]bool{"errors": true}
	for _, s := range settings {
		if s.EnvVar == "" {
			continue
		}
		if err := writeEnvCase(&body, s, imports); err != nil {
			return nil, fmt.Errorf("apply env: %s: %w", s.EnvVar, err)
		}
	}

	var b bytes.Buffer
	b.WriteString(generatedHeader)
	fmt.Fprintf(&b, "package %s\n\nimport (\n", pkg)
	for _, path := range slices.Sorted(maps.Keys(imports)) {
		fmt.Fprintf(&b, "\t%q\n", path)
	}
	fmt.Fprintf(&b, "\n\t%q\n)\n\n", target.Import)
	b.WriteString("// ApplyEnv overlays the environment on cfg and returns every value it\n")
	b.WriteString("// refused, joined; a refused variable leaves its field as it was. getenv\n")
	b.WriteString("// is called once per variable: os.Getenv, or a map lookup in a test.\n")
	fmt.Fprintf(&b, "func ApplyEnv(cfg *%s, getenv func(string) string) error {\n", target.Type)
	if target.EnvCheck != "" {
		fmt.Fprintf(&b, "\terrs := []error{%s(getenv)}\n", target.EnvCheck)
	} else {
		b.WriteString("\tvar errs []error\n")
	}
	b.Write(body.Bytes())
	b.WriteString("\treturn errors.Join(errs...)\n}\n")
	if slices.ContainsFunc(settings, readsBool) {
		b.WriteString(parseBoolEnvSource)
	}
	return gofmt("apply env", b.Bytes())
}

func readsBool(s configuration.Setting) bool {
	return s.EnvVar != "" && (s.Kind == command.Bool || s.Kind == command.OptionalBool)
}

// writeEnvCase writes the statement that reads one variable into its field.
func writeEnvCase(b *bytes.Buffer, s configuration.Setting, imports map[string]bool) error {
	if s.GoPath == "" {
		return fmt.Errorf("no GoPath to store into")
	}
	dst := "cfg." + s.GoPath
	fmt.Fprintf(b, "\tif v := getenv(%q); v != \"\" {\n", s.EnvVar)
	refuse := fmt.Sprintf("errs = append(errs, fmt.Errorf(\"%s: %%w\", err))", s.EnvVar)
	parsed := func(call, name string) {
		fmt.Fprintf(b, "\t\tif %s, err := %s; err != nil {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s = %s\n\t\t}\n", name, call, refuse, dst, name)
	}
	if s.Kind != command.String && s.Kind != command.StringList {
		imports["fmt"] = true
	}
	switch s.Kind {
	case command.String:
		fmt.Fprintf(b, "\t\t%s = v\n", dst)
	case command.Int:
		imports["strconv"] = true
		parsed("strconv.Atoi(v)", "n")
	case command.Bool:
		imports["strings"] = true
		parsed("parseBoolEnv(v)", "b")
	case command.Float:
		imports["strconv"] = true
		parsed("strconv.ParseFloat(v, 64)", "f")
	case command.Duration:
		imports["time"] = true
		parsed("time.ParseDuration(v)", "d")
	case command.OptionalBool:
		imports["strings"] = true
		fmt.Fprintf(b, "\t\tif b, err := parseBoolEnv(v); err != nil {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s = &b\n\t\t}\n", refuse, dst)
	case command.Text:
		if s.Floor {
			fmt.Fprintf(b, "\t\tfloor := %s\n\t\tif err := floor.UnmarshalText([]byte(v)); err != nil {\n\t\t\t%s\n\t\t} else if %s.WeakerThan(floor) {\n\t\t\t%s = floor\n\t\t}\n", dst, refuse, dst, dst)
			break
		}
		fmt.Fprintf(b, "\t\tif err := %s.UnmarshalText([]byte(v)); err != nil {\n\t\t\t%s\n\t\t}\n", dst, refuse)
	case command.StringList:
		imports["strings"] = true
		fmt.Fprintf(b, "\t\tparts := strings.Split(v, \",\")\n\t\tout := parts[:0]\n\t\tfor _, p := range parts {\n\t\t\tif p = strings.TrimSpace(p); p != \"\" {\n\t\t\t\tout = append(out, p)\n\t\t\t}\n\t\t}\n\t\t%s = out\n", dst)
	default:
		return fmt.Errorf("a %s setting has no variable form", s.Kind)
	}
	b.WriteString("\t}\n")
	return nil
}

// parseBoolEnvSource refuses a typo like "ture" rather than keeping the
// previous value: a silently kept default is misconfiguration nobody sees.
const parseBoolEnvSource = `
// parseBoolEnv accepts true/1/yes and false/0/no in any case.
func parseBoolEnv(v string) (bool, error) {
	switch strings.ToLower(v) {
	case "true", "1", "yes":
		return true, nil
	case "false", "0", "no":
		return false, nil
	}
	return false, fmt.Errorf("%q is not a boolean, use true or false", v)
}
`

// writeConfigBinder writes BindFlags, which registers a flag per setting
// that has one, storing into the target struct.
func writeConfigBinder(b *bytes.Buffer, settings []configuration.Setting, target Target) error {
	b.WriteString("\n// BindFlags registers a flag per setting on fs, storing into cfg. Call it\n")
	b.WriteString("// after loading cfg, so a flag the caller does not pass keeps cfg's value.\n")
	fmt.Fprintf(b, "func BindFlags(fs *flag.FlagSet, cfg *%s) {\n", target.Type)
	for _, s := range settings {
		if s.Flag.Long == "" {
			continue
		}
		method, ok := settingBindMethods[s.Kind]
		if !ok {
			return fmt.Errorf("bind flags: --%s: a %s setting has no flag form", s.Flag.Long, s.Kind)
		}
		dst := "cfg." + s.GoPath
		fmt.Fprintf(b, "\tfs.%sVar(&%s, %q, %s, %q)\n", method, dst, s.Flag.Long, dst, s.Usage)
		if s.Flag.Short != "" {
			fmt.Fprintf(b, "\tfs.%sVar(&%s, %q, %s, %q)\n", method, dst, s.Flag.Short, dst, "Short for --"+s.Flag.Long)
		}
	}
	b.WriteString("}\n")
	return nil
}

var settingBindMethods = map[command.Kind]string{
	command.String: "String", command.Int: "Int", command.Bool: "Bool",
	command.Float: "Float64", command.Duration: "Duration", command.Text: "Text",
}

func gofmt(what string, src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("%s: gofmt the generated source: %w", what, err)
	}
	return out, nil
}
